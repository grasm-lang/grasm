"""Write the calendar tables that only ICU can give into their packages.

Three calendars are not arithmetic: Umm al-Qura (Saudi Arabia's official
Hijri calendar, set by observation and published as a table), the
Japanese eras (236 of them since 645, set by proclamation), and the
Chinese and Korean lunisolar calendars (astronomical: new moons and solar
terms, which ICU computes). Each table is read from the ICU inside Node by
formatting every day of its range, never typed:

    python3 scripts/gen_calendars.py hijri packages/hijri/src/main.gr
    python3 scripts/gen_calendars.py --check chinese packages/chinesecal/src/main.gr

The table replaces whatever is between `BEGIN GENERATED` and `END
GENERATED`; `--check` fails when it would change.
"""
import json
import re
import subprocess
import sys

NODE = r"""
const kind = process.argv[1];
const day = 86400000;
function parts(cal, d, opts) {
  const f = new Intl.DateTimeFormat("en-u-ca-" + cal, Object.assign({timeZone: "UTC"}, opts));
  return f;
}
const out = [];
if (kind === "hijri") {
  const f = parts("islamic-umalqura", 0, {year: "numeric", month: "numeric", day: "numeric"});
  for (let d = -32000; d < 75000; d++) {
    const p = Object.fromEntries(f.formatToParts(new Date(d * day)).map(x => [x.type, x.value]));
    const y = +p.year, m = +p.month;
    if (+p.day === 1 && y >= 1300 && (y <= 1600 || (y === 1601 && m === 1))) out.push([d, y, m]);
  }
} else if (kind === "japanese") {
  const f = parts("japanese", 0, {era: "long", year: "numeric"});
  const g = parts("gregory", 0, {year: "numeric"});
  let last = null;
  for (let d = -483000; d < 25000; d++) {
    const p = f.formatToParts(new Date(d * day));
    const era = p.find(x => x.type === "era").value;
    if (era !== last) {
      // The calendar year in which this era's year 1 falls, as ICU counts
      // years (Julian before 1582): the first era began before the scan.
      const gy = +g.formatToParts(new Date(d * day)).find(x => x.type === "year").value;
      out.push([d, era, gy - +p.find(x => x.type === "year").value + 1]);
      last = era;
    }
  }
} else {
  const f = parts(kind, 0, {year: "numeric", month: "numeric", day: "numeric"});
  for (let d = -25500; d < 47600; d++) {
    const p = Object.fromEntries(f.formatToParts(new Date(d * day)).map(x => [x.type, x.value]));
    if (+p.day === 1) out.push([d, +p.relatedYear, parseInt(p.month), p.month.endsWith("bis") ? 1 : 0]);
  }
}
process.stdout.write(JSON.stringify(out));
"""


def node_rows(kind):
    run = subprocess.run(["node", "-e", NODE, kind], capture_output=True, text=True, check=True)
    return json.loads(run.stdout)


def node_version():
    return subprocess.run(["node", "-p", "process.versions.icu"], capture_output=True, text=True, check=True).stdout.strip()


def rows_to_list(values, per_line=12):
    lines = []
    for k in range(0, len(values), per_line):
        lines.append(", ".join(str(v) for v in values[k:k + per_line]))
    return "[" + ",\n        ".join(lines) + "]"


def block(kind):
    icu = node_version()
    head = f"// BEGIN GENERATED by scripts/gen_calendars.py from ICU {icu}\n"
    rows = node_rows("chinese" if kind == "chinese" else kind)
    if kind == "hijri":
        assert rows[0][1:] == [1300, 1] and rows[-1][1:] == [1601, 1], rows[:1] + rows[-1:]
        starts = [r[0] for r in rows]
        return head + ("/// The first day (Unix day number) of each Umm al-Qura month from\n"
                       "/// Muharram 1300 to Dhu al-Hijjah 1600, and one past the last.\n"
                       "fn umalqura_starts() -> [i64] {\n    " + rows_to_list(starts) + "\n}\n// END GENERATED")
    if kind == "japanese":
        days = rows_to_list([r[0] for r in rows])
        years = rows_to_list([r[2] for r in rows])
        names = "[" + ",\n        ".join(json.dumps(r[1], ensure_ascii=False) for r in rows) + "]"
        return head + ("/// Each era's first day (Unix day number) -- the first stands for every\n"
                       "/// day before the second -- the year in which its year 1 falls, and its\n"
                       "/// English name as ICU gives it.\nfn era_starts() -> [i64] {\n    " + days + "\n}\n\n"
                       "fn era_first_years() -> [i64] {\n    " + years + "\n}\n\n"
                       "fn era_names() -> [str] {\n    " + names + "\n}\n// END GENERATED")
    # Months whose related year is 1900 to 2100, the last of them standing
    # only for where 2100's last month ends.
    korean = [r for r in node_rows("dangi") if r[1] <= 2100]
    rows = [r for r in rows if r[1] <= 2100]
    flat = [v for r in rows for v in r]
    kflat = [v for r in korean for v in r]
    return head + ("/// Each month's first day (Unix day), related Gregorian year, month and\n"
                   "/// whether it is a leap month, as (day, year, month, leap) in a row.\n"
                   "fn chinese_months() -> [i64] {\n    " + rows_to_list(flat) + "\n}\n\n"
                   "fn korean_months() -> [i64] {\n    " + rows_to_list(kflat) + "\n}\n// END GENERATED")


args = sys.argv[1:]
check = args and args[0] == "--check"
if check:
    args = args[1:]
kind, path = args
text = open(path).read()
pattern = re.compile(r"// BEGIN GENERATED.*?// END GENERATED", re.S)
if not pattern.search(text):
    sys.exit(f"{path}: no BEGIN GENERATED / END GENERATED block")
out = pattern.sub(lambda _: block(kind), text)
if check:
    if out != text:
        sys.exit(f"{path}: the {kind} table is not what ICU {node_version()} gives")
    print(f"{path}: {kind} table matches ICU {node_version()}")
else:
    open(path, "w").write(out)
    print(f"{path}: wrote the {kind} table")
