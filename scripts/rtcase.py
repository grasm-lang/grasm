#!/usr/bin/env python3
"""Writes compiler/rt/src/casemap.gr from what the Rust runtime says of case.

    python3 scripts/rtcase.py <dump>

<dump> is `compiler/rt/probe/casedump.gr`'s output, built with
`grasm build --native` on the Rust runtime and run with no arguments: for
every scalar value, its lowercase and uppercase where they differ (`L`, `U`)
and what the final-sigma rule sees in it (`I` skipped as case-ignorable, `C`
cased and not skipped). Nothing here is Unicode's own data: the tables are
the Rust runtime's answers, so the Grasm runtime gives the same ones, and
`scripts/fuzz_rtcase.sh` compares the two over every code point. When the
Rust toolchain's Unicode moves, that gate fails and this is run again.
"""
import sys

lower, upper, ignorable, cased = [], [], [], []
for line in open(sys.argv[1]):
    f = line.split()
    if not f:
        continue
    kind, cp = f[0], int(f[1], 16)
    if kind in ("L", "U"):
        out = [int(x, 16) for x in f[2:]]
        if not 1 <= len(out) <= 3:
            sys.exit(f"rtcase: {line.strip()!r} maps to {len(out)} code points")
        (lower if kind == "L" else upper).append((cp, out))
    elif kind == "I":
        ignorable.append(cp)
    elif kind == "C":
        cased.append(cp)
    else:
        sys.exit(f"rtcase: unexpected line {line.strip()!r}")
if len(lower) < 1000 or len(upper) < 1000 or len(ignorable) < 1000 or len(cased) < 1000:
    sys.exit("rtcase: the dump is too short to be every code point's")


def ranges(cps):
    out = []
    for c in sorted(cps):
        if out and out[-1][1] + 1 == c:
            out[-1][1] = c
        else:
            out.append([c, c])
    return out


def maps_text(pairs):
    return ",".join(" ".join(f"{x:x}" for x in [cp] + out) for cp, out in sorted(pairs))


def ranges_text(cps):
    return ",".join(f"{a:x} {b:x}" for a, b in ranges(cps))


def literal(name, doc, text):
    # A string literal: `{` would open an interpolation, and none of this
    # text has one, nor a quote or a backslash.
    assert not any(c in text for c in '{}"\\')
    lines = [f"/// {doc}", f"fn {name}() -> addr {{", f'    unsafe {{ mem_static("{text}") }}', "}", ""]
    lines += [f"fn {name}_len() -> i64 {{", f'    unsafe {{ mem_static_len("{text}") }}', "}", ""]
    return "\n".join(lines)


out = [
    "// Generated by scripts/rtcase.py from compiler/rt/probe/casedump.gr run on",
    "// the Rust runtime; do not edit. The case of every scalar value as the Rust",
    "// runtime has it: lowercase and uppercase where they differ, each one to",
    "// three code points, and the two sets the final-sigma rule reads -- what it",
    "// skips as case-ignorable and what it takes as cased. Hex, records split",
    "// by `,` and their fields by spaces; `case.gr` reads them once.",
    "",
    literal("lower_text", f"{len(lower)} code points and their lowercase.", maps_text(lower)),
    literal("upper_text", f"{len(upper)} code points and their uppercase.", maps_text(upper)),
    literal("ignorable_text", f"{len(ignorable)} case-ignorable code points, as ranges.", ranges_text(ignorable)),
    literal("cased_text", f"{len(cased)} cased code points the rule does not skip, as ranges.", ranges_text(cased)),
]
text = "\n".join(out).rstrip("\n") + "\n"
# Every function here is read by `case.gr`.
text = text.replace("\nfn ", "\npub fn ")
open("compiler/rt/src/casemap.gr", "w").write(text)
print(f"casemap.gr: lowercase {len(lower)}, uppercase {len(upper)}, ignorable {len(ignorable)} ({len(ranges(ignorable))} ranges), cased {len(cased)} ({len(ranges(cased))} ranges)")
