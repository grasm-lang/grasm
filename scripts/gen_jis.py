"""Generate the tables of `packages/jisx0212` and `packages/jisx0213`.

Every table comes from Python's codecs:

- JIS X 0212 from what `euc_jp` decodes each `0x8F` triple to;
- JIS X 0213 from what `euc_jis_2004` and `euc_jisx0213` decode each pair
  and triple to, plane 1 at `A1A1`-`FEFE` and plane 2 at `8FA1A1`-
  `8FFEFE` in the rows JIS X 0212 leaves empty;
- the cells Shift_JIS-2004 reads differently from EUC-JIS-2004 (JIS X 0201
  Roman puts the backslash and tilde there);
- for each encoding form, the code points whose encoding is not what the
  package's default table would write: the generator builds that default
  exactly as the package does and keeps only the cases where Python's
  encoder disagrees, so the list is short and every entry is a decision
  the reference encoder actually makes.

    python3 scripts/gen_jis.py           # rewrite both packages' tables
    python3 scripts/gen_jis.py --check   # fail if either is stale

Each package's own code sits above the marker line; everything below it
is this script's.
"""
import sys

MARKER = "// ---- Generated by scripts/gen_jis.py from Python's codecs. Do not edit below. ----"
PLANE2_ROWS = [1, 3, 4, 5, 8, 12, 13, 14, 15] + list(range(78, 95))
CODE_POINTS = list(range(0, 0xD800)) + list(range(0xE000, 0x10000)) + list(range(0x20000, 0x2B820))


def dec(raw, codec):
    try:
        return raw.decode(codec)
    except Exception:
        return None


def enc(text, codec):
    try:
        return text.encode(codec)
    except Exception:
        return None


def packed(raw):
    v = 0
    for b in raw:
        v = v * 256 + b
    return v


def x0212():
    cells = {}
    for row in range(1, 95):
        for cell in range(1, 95):
            text = dec(bytes([0x8F, row + 0xA0, cell + 0xA0]), "euc_jp")
            if text is not None:
                assert len(text) == 1
                cells[(row, cell)] = ord(text)
    return cells


def sjis_pair(plane, row, cell):
    if plane == 1:
        lead = (row + 0x101) // 2 if row <= 62 else (row + 0x181) // 2
    elif row <= 15:
        lead = (row + 0x1DF) // 2 - (row // 8) * 3
    else:
        lead = (row + 0x19B) // 2
    trail = cell + 0x9E if row % 2 == 0 else cell + 0x3F + (1 if cell >= 64 else 0)
    return bytes([lead, trail])


def euc_bytes(plane, row, cell):
    raw = bytes([row + 0xA0, cell + 0xA0])
    return raw if plane == 1 else b"\x8f" + raw


def places():
    for row in range(1, 95):
        for cell in range(1, 95):
            yield 1, row, cell
    for row in PLANE2_ROWS:
        for cell in range(1, 95):
            yield 2, row, cell


def x0213(euc_codec, sjis_codec):
    cells, sjis_reads = {}, {}
    for p in places():
        text = dec(euc_bytes(*p), euc_codec)
        other = dec(sjis_pair(*p), sjis_codec)
        if text is not None:
            cells[p] = [ord(c) for c in text]
        if other != text:
            assert other is not None and text is not None and len(other) == 1, (p, text, other)
            sjis_reads[p] = ord(other)
    return cells, sjis_reads


def default_encoder(form, cells, sjis_reads, j0212):
    """What the package builds before its preference list is applied."""
    out = {}
    for p in places():
        codes = cells.get(p)
        if form == "sjis" and p in sjis_reads:
            codes = [sjis_reads[p]]
        if codes is None or len(codes) != 1 or codes[0] in out:
            continue
        out[codes[0]] = packed(sjis_pair(*p) if form == "sjis" else euc_bytes(*p))
    if form == "euc":
        for (row, cell), code in sorted(j0212.items()):
            if row not in PLANE2_ROWS and code not in out:
                out[code] = packed(bytes([0x8F, row + 0xA0, cell + 0xA0]))
        for k in range(0xFF61, 0xFFA0):
            out.setdefault(k, 0x8E00 + k - 0xFF61 + 0xA1)
    else:
        for k in range(0xFF61, 0xFFA0):
            out.setdefault(k, k - 0xFF61 + 0xA1)
        out.setdefault(0xA5, 0x5C)
        out.setdefault(0x203E, 0x7E)
    return out


def preferences(codec, default):
    prefs = []
    for cp in CODE_POINTS:
        want = enc(chr(cp), codec)
        have = default.get(cp, cp if cp < 0x80 else None)
        want_v = None if want is None else packed(want)
        if want_v != have:
            prefs.append((cp, 0 if want_v is None else want_v))
    return prefs


def eucjp_preferences(j0212):
    """EUC-JP's encoder against the package's default: JIS X 0208 as
    Python's `shift_jis` writes it, moved to EUC rows, then JIS X 0212."""
    default = {}
    for cp in CODE_POINTS:
        raw = enc(chr(cp), "shift_jis")
        if raw is not None and len(raw) == 2:
            lead, trail = raw
            row = lead * 2 - (257 if lead < 224 else 385)
            if trail >= 159:
                row, cell = row + 1, trail - 158
            else:
                cell = trail - 63 - (1 if trail >= 128 else 0)
            default[cp] = packed(bytes([row + 0xA0, cell + 0xA0]))
    for (row, cell), code in sorted(j0212.items()):
        default.setdefault(code, packed(bytes([0x8F, row + 0xA0, cell + 0xA0])))
    for k in range(0xFF61, 0xFFA0):
        default.setdefault(k, 0x8E00 + k - 0xFF61 + 0xA1)
    return preferences("euc_jp", default)


def words(name, doc, entries):
    out = [doc, f"fn {name}() -> str {{"]
    if not entries:
        return out + ['    return ""', "}", ""]
    lines, line = [], ""
    for word in entries:
        if line and len(line) + 1 + len(word) > 64:
            lines.append(line)
            line = word
        else:
            line = (line + " " + word) if line else word
    lines.append(line)
    out.append(f'    return "{lines[0]} "' + (" +" if len(lines) > 1 else ""))
    for i, piece in enumerate(lines[1:]):
        out.append(f'    "{piece} "' + (" +" if i < len(lines) - 2 else ""))
    return out + ["}", ""]


def rows_fn(name, doc, rows, width):
    out = [doc, f"fn {name}() -> [str] {{", "    return ["]
    for row in rows:
        out.append('        "' + "".join(("%0" + str(width) + "X") % v for v in row) + '",')
    return out + ["    ]", "}", ""]


def mkt(p):
    return "%x" % (p[0] * 65536 + p[1] * 256 + p[2])


def gen_0212():
    j = x0212()
    rows = sorted({r for r, _ in j})
    out = [MARKER, "", "/// The rows JIS X 0212 uses.", "fn x0212_rows() -> [i64] {",
           "    return [%s]" % ", ".join(map(str, rows)), "}", ""]
    out += rows_fn("x0212_cells", "/// One string per row, four hexadecimal digits per cell, 0 where\n"
                   "/// the cell is empty.", [[j.get((r, c), 0) for c in range(1, 95)] for r in rows], 4)
    prefs = eucjp_preferences(j)
    out += words("packed_eucjp_preferred", "/// Code points EUC-JP writes other than the default table would, as\n"
                 "/// `codepoint:bytes`; bytes 0 means Python's encoder refuses it.",
                 ["%x:%x" % kv for kv in prefs])
    return "\n".join(out) + "\n", f"jisx0212: {len(j)} cells in {len(rows)} rows, {len(prefs)} EUC-JP preferences"


def gen_0213():
    j = x0212()
    c04, s04 = x0213("euc_jis_2004", "shift_jis_2004")
    c00, s00 = x0213("euc_jisx0213", "shift_jisx0213")
    assert s04 == s00
    width = 6
    seqs = sorted((p, v) for p, v in c04.items() if len(v) > 1)
    assert all(c00.get(p) == v for p, v in seqs)
    edition = []
    for p in places():
        a, b = c04.get(p), c00.get(p)
        if a != b:
            assert b is None or len(b) == 1
            edition.append("%s:%x" % (mkt(p), 0 if b is None else b[0]))
    out = [MARKER, "", "/// The rows plane 2 uses, which are the ones JIS X 0212 leaves empty.",
           "fn plane2_rows() -> [i64] {", "    return [%s]" % ", ".join(map(str, PLANE2_ROWS)), "}", ""]
    doc = "/// One string per row of plane %d, %d hexadecimal digits per cell, 0 where\n" \
          "/// the cell is empty or holds a sequence; the 2004 edition."
    out += rows_fn("plane1", doc % (1, width),
                   [[c04[(1, r, c)][0] if len(c04.get((1, r, c), [0, 0])) == 1 else 0 for c in range(1, 95)]
                    for r in range(1, 95)], width)
    out += rows_fn("plane2", doc % (2, width),
                   [[c04[(2, r, c)][0] if len(c04.get((2, r, c), [0, 0])) == 1 else 0 for c in range(1, 95)]
                    for r in PLANE2_ROWS], width)
    out += words("packed_sequences", "/// Cells that stand for two code points, a letter and a combining mark,\n"
                 "/// as `cell:codepoint,codepoint`. A cell is plane, row and cell, a byte each.",
                 ["%s:%s" % (mkt(p), ",".join("%x" % c for c in v)) for p, v in seqs])
    out += words("packed_sjis_reads", "/// Cells Shift_JIS reads as a different code point from EUC, as\n"
                 "/// `cell:codepoint`.", ["%s:%x" % (mkt(p), v) for p, v in sorted(s04.items())])
    out += words("packed_edition_2000", "/// Cells JIS X 0213:2000 holds differently, as `cell:codepoint`; 0 is\n"
                 "/// a cell the 2004 edition added.", edition)
    counts = []
    for name, codec, form, cells in (("sjis_2004", "shift_jis_2004", "sjis", c04),
                                     ("euc_2004", "euc_jis_2004", "euc", c04),
                                     ("sjis_2000", "shift_jisx0213", "sjis", c00),
                                     ("euc_2000", "euc_jisx0213", "euc", c00)):
        prefs = preferences(codec, default_encoder(form, cells, s04, j))
        counts.append(f"{name} {len(prefs)}")
        out += words("preferred_" + name, f"/// Python's `{codec}` encoder where it departs from the default table,\n"
                     "/// as `codepoint:bytes`; bytes 0 means it refuses the character.",
                     ["%x:%x" % kv for kv in prefs])
    return "\n".join(out) + "\n", (f"jisx0213: {sum(1 for v in c04.values() if len(v) == 1)} cells, {len(seqs)} sequences, "
                                   f"{len(s04)} Shift_JIS readings, {len(edition)} edition differences; preferences " +
                                   ", ".join(counts))


def main():
    check = "--check" in sys.argv
    stale = False
    for path, gen in (("packages/jisx0212/src/main.gr", gen_0212), ("packages/jisx0213/src/main.gr", gen_0213)):
        text, summary = gen()
        current = open(path).read()
        head = current.split(MARKER)[0]
        new = head + text
        if check:
            if new != current:
                print(f"{path} is stale; run python3 scripts/gen_jis.py")
                stale = True
        else:
            open(path, "w").write(new)
        print(summary)
    sys.exit(1 if stale else 0)


if __name__ == "__main__":
    main()
