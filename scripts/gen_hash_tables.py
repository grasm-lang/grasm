"""Generate the constant tables of B34's hashes into their packages.

- RIPEMD-160's word-order and rotation tables and its initial value are
  read from golang.org/x/crypto/ripemd160 in the module cache.
- Whirlpool's S-box is found in OpenSSL's libcrypto by shape (a run of 256
  values that is a permutation, read with a stride of 8, 16 or 64 bytes, as
  a byte lane of its 64-bit round tables), and kept only if a reference model
  of Whirlpool built on it hashes exactly as OpenSSL does.

Each table goes below a marker line at the end of its package; with
--check nothing is written and the exit status says whether they are
current.
"""
import ctypes
import os
import random
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(ROOT, "scripts"))
sys.path.insert(0, os.path.join(ROOT, "scripts/lib"))
import evp  # noqa: E402
from gen_cipher_tables import MARKER as _UNUSED, go_array, go_crypto, render  # noqa: E402,F401

MARKER = "// --- Generated by scripts/gen_hash_tables.py; do not edit below this line. ---"


def openssl_digest(name, data):
    L = evp.L
    L.EVP_MD_fetch.restype = ctypes.c_void_p
    L.EVP_MD_fetch.argtypes = [ctypes.c_void_p, ctypes.c_char_p, ctypes.c_char_p]
    L.EVP_Digest.argtypes = [ctypes.c_char_p, ctypes.c_size_t, ctypes.c_char_p, ctypes.POINTER(ctypes.c_uint),
                             ctypes.c_void_p, ctypes.c_void_p]
    md = L.EVP_MD_fetch(None, name.encode(), None)
    out = ctypes.create_string_buffer(64)
    n = ctypes.c_uint(0)
    assert L.EVP_Digest(data, len(data), out, ctypes.byref(n), md, None) == 1
    return out.raw[:n.value]


def gf_mul(a, b):
    r = 0
    while b:
        if b & 1:
            r ^= a
        a <<= 1
        if a & 0x100:
            a ^= 0x11D
        b >>= 1
    return r


def whirlpool(sbox, msg):
    """ISO/IEC 10118-3 Whirlpool on an 8x8 byte state, row-major."""
    c = [1, 1, 4, 1, 8, 5, 2, 9]

    def rho(a, k):
        g = [sbox[x] for x in a]
        p = [g[8 * ((i - j) % 8) + j] for i in range(8) for j in range(8)]
        t = []
        for i in range(8):
            for j in range(8):
                v = 0
                for q in range(8):
                    v ^= gf_mul(p[8 * i + q], c[(j - q) % 8])
                t.append(v)
        return [x ^ y for x, y in zip(t, k)]

    def w(key, block):
        k = key
        s = [x ^ y for x, y in zip(block, k)]
        for r in range(1, 11):
            rc = [sbox[8 * (r - 1) + j] for j in range(8)] + [0] * 56
            k = rho(k, rc)
            s = rho(s, k)
        return s
    bits = len(msg) * 8
    data = msg + b"\x80"
    while len(data) % 64 != 32:
        data += b"\0"
    data += bits.to_bytes(32, "big")
    h = [0] * 64
    for at in range(0, len(data), 64):
        m = list(data[at:at + 64])
        h = [x ^ y ^ z for x, y, z in zip(w(h, m), h, m)]
    return bytes(h)


def whirlpool_sbox():
    # Whirlpool is in the legacy provider, a module beside libcrypto.
    legacy = os.path.join(os.path.dirname(evp._path), "ossl-modules", "legacy.dylib")
    data = open(evp._path, "rb").read() + (open(legacy, "rb").read() if os.path.exists(legacy) else b"")
    seen = set()
    # OpenSSL stores each 64-bit table entry in all eight rotations, so an
    # entry's lanes are 64 bytes apart; 8 and 16 cover the other layouts.
    for stride in (8, 16, 64):
        for start in range(stride):
            stream = data[start::stride]
            count, distinct = [0] * 256, 0
            for i, v in enumerate(stream):
                if count[v] == 0:
                    distinct += 1
                count[v] += 1
                if i >= 256:
                    u = stream[i - 256]
                    count[u] -= 1
                    if count[u] == 0:
                        distinct -= 1
                if i >= 255 and distinct == 256:
                    seen.add(bytes(stream[i - 255:i + 1]))
    rng = random.Random(1)
    msgs = [b"", b"abc"] + [bytes(rng.randrange(256) for _ in range(rng.randrange(0, 200))) for _ in range(3)]
    want = [openssl_digest("WHIRLPOOL", m) for m in msgs]
    hits = [list(s) for s in seen if [whirlpool(list(s), m) for m in msgs[:1]] == want[:1]]
    hits = [s for s in hits if all(whirlpool(s, m) == w for m, w in zip(msgs, want))]
    if len(hits) != 1:
        raise SystemExit(f"Whirlpool: {len(hits)} of {len(seen)} candidate S-boxes fit OpenSSL, not exactly one")
    return hits[0]


def tables():
    rp = f"{go_crypto()}/ripemd160"
    out = {"ripemd160": {
        "RIPEMD_IV": [int(x, 16) for x in ("67452301", "efcdab89", "98badcfe", "10325476", "c3d2e1f0")],
        "RIPEMD_N": go_array(f"{rp}/ripemd160block.go", "_n"),
        "RIPEMD_R": go_array(f"{rp}/ripemd160block.go", "_r"),
        "RIPEMD_N2": go_array(f"{rp}/ripemd160block.go", "n_"),
        "RIPEMD_R2": go_array(f"{rp}/ripemd160block.go", "r_"),
    }}
    src = open(f"{rp}/ripemd160.go").read()
    iv = [int(src.split(f"_s{i} = ")[1].split()[0], 16) for i in range(5)]
    if iv != out["ripemd160"]["RIPEMD_IV"]:
        raise SystemExit("RIPEMD-160: initial value differs from x/crypto's")
    out["ripemd160"]["RIPEMD_IV"] = iv
    out["whirlpool"] = {"WHIRLPOOL_SBOX": whirlpool_sbox()}
    return out


def main():
    check = "--check" in sys.argv
    stale = []
    for pkg, tabs in tables().items():
        path = os.path.join(ROOT, "packages", pkg, "src", "main.gr")
        src = open(path).read()
        head = src.split(MARKER)[0].rstrip("\n")
        body = "\n\n".join(render(n, v, max(v) > 255) for n, v in tabs.items())
        new = f"{head}\n\n{MARKER}\n\n{body}\n"
        if new != src:
            stale.append(pkg)
            if not check:
                open(path, "w").write(new)
    if check and stale:
        print("stale tables:", " ".join(stale)); sys.exit(1)
    print("tables current" if check else f"wrote: {' '.join(stale) or 'nothing'}")


if __name__ == "__main__":
    main()
