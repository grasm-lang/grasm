"""Write Node's built-in module names into packages/npmname.

validate-npm-package-name warns about a name that is a core module; the
list is `require('module').builtinModules` of the Node it runs on, so it is
read from Node rather than typed:

    python3 scripts/gen_npmname.py packages/npmname/src/main.gr
    python3 scripts/gen_npmname.py --check packages/npmname/src/main.gr
"""
import json
import re
import subprocess
import sys

args = sys.argv[1:]
check = args and args[0] == "--check"
path = args[-1]
names = json.loads(subprocess.run(["node", "-p", "JSON.stringify(require('module').builtinModules)"],
                                  capture_output=True, text=True, check=True).stdout)
version = subprocess.run(["node", "--version"], capture_output=True, text=True, check=True).stdout.strip()
rows, line = [], []
for n in names:
    line.append(json.dumps(n))
    if len(", ".join(line)) > 100:
        rows.append(", ".join(line))
        line = []
if line:
    rows.append(", ".join(line))
block = (f"// BEGIN GENERATED by scripts/gen_npmname.py from Node {version}\n"
         "fn builtins() -> [str] {\n    [" + ",\n        ".join(rows) + "]\n}\n// END GENERATED")
text = open(path).read()
pattern = re.compile(r"// BEGIN GENERATED.*?// END GENERATED", re.S)
out = pattern.sub(lambda _: block, text)
if check:
    if out != text:
        sys.exit(f"{path}: the built-in module list is not what Node {version} says")
    print(f"{path}: built-in module list matches Node {version}")
else:
    open(path, "w").write(out)
    print(f"{path}: wrote {len(names)} built-in module names")
