"""Write the terminfo capability names, by index, into packages/terminfo.

A compiled terminfo entry stores capabilities by position — the fourth
boolean, the three-hundredth string — and the names for those positions are
ncurses' own table. This does not type that table. It writes compiled
entries that set each position to a value naming it, asks `infocmp` to print
them, and reads the names back, so the table is whatever the installed
ncurses says:

    python3 scripts/gen_terminfo_caps.py packages/terminfo/src/main.gr

`infocmp -x` is asked, because without it the obsolete termcap
capabilities (`OTbs` and the like) are not printed and their positions would
have no names. The names replace whatever is between the `BEGIN GENERATED`
and `END GENERATED` lines.
"""
import os
import re
import shutil
import struct
import subprocess
import sys
import tempfile


def counts():
    sdk = subprocess.run(["xcrun", "--show-sdk-path"], capture_output=True,
                         text=True).stdout.strip()
    text = open(os.path.join(sdk, "usr/include/term.h")).read()
    return tuple(int(re.search(r"#define %s\s+(\d+)" % n, text).group(1))
                 for n in ("BOOLCOUNT", "NUMCOUNT", "STRCOUNT"))


def compiled(bools, nums, strs):
    names = b"tall|every capability\0"
    body = names + bytes(bools)
    if len(body) % 2:
        body += b"\0"
    table, offsets = b"", []
    for s in strs:
        if s is None:
            offsets.append(-1)
        else:
            offsets.append(len(table))
            table += s + b"\0"
    head = struct.pack("<6h", 0o432, len(names), len(bools), len(nums),
                       len(strs), len(table))
    return (head + body + b"".join(struct.pack("<h", n) for n in nums) +
            b"".join(struct.pack("<h", o) for o in offsets) + table)


def dump(work, data):
    os.makedirs(os.path.join(work, "74"), exist_ok=True)
    open(os.path.join(work, "74", "tall"), "wb").write(data)
    out = subprocess.run(["infocmp", "-1", "-x", "-A", work, "tall"],
                         capture_output=True, text=True).stdout
    return [line.strip().rstrip(",") for line in out.split("\n")[2:] if line.strip()]


def main():
    path = sys.argv[1]
    nbool, nnum, nstr = counts()
    work = tempfile.mkdtemp()
    strings = [""] * nstr
    # Each string holds its own index behind a zero. `infocmp` re-sorts
    # `acsc` as pairs by their first character, and "0146" is already in
    # order, where "s146" came back as "46s1".
    for line in dump(work, compiled([0] * nbool, [-1] * nnum,
                                    [b"0%03d" % i for i in range(nstr)])):
        m = re.fullmatch(r"(\w+)=0(\d{3})", line)
        if m:
            strings[int(m.group(2))] = m.group(1)
    numbers = [""] * nnum
    for line in dump(work, compiled([0] * nbool, [i + 1 for i in range(nnum)],
                                    [None] * nstr)):
        m = re.fullmatch(r"(\w+)#(\d+)", line)
        if m:
            numbers[int(m.group(2)) - 1] = m.group(1)
    booleans = [""] * nbool
    for i in range(nbool):
        flags = [0] * nbool
        flags[i] = 1
        shown = dump(work, compiled(flags, [-1] * nnum, [None] * nstr))
        if shown:
            booleans[i] = shown[0]
    shutil.rmtree(work)
    version = subprocess.run(["infocmp", "-V"], capture_output=True,
                             text=True).stdout.strip()
    lines = ["// BEGIN GENERATED by scripts/gen_terminfo_caps.py from " + version]
    for name, values in (("BOOLEAN_NAMES", booleans), ("NUMBER_NAMES", numbers),
                         ("STRING_NAMES", strings)):
        packed = ",".join(values)
        lines.append("let %s = (\"\" +" % name)
        chunk = 70
        pieces = [packed[i:i + chunk] for i in range(0, len(packed), chunk)]
        for j, piece in enumerate(pieces):
            lines.append("    \"%s\"%s" % (piece, " +" if j + 1 < len(pieces) else ")"))
        lines.append("    .split(\",\")")
    source = open(path, encoding="utf-8").read()
    begin = source.index("// BEGIN GENERATED")
    end = source.index("// END GENERATED")
    open(path, "w", encoding="utf-8").write(source[:begin] + "\n".join(lines) + "\n" +
                                            source[end:])
    print("%d booleans, %d numbers, %d strings; %d, %d, %d shown" % (
        nbool, nnum, nstr, sum(1 for b in booleans if b),
        sum(1 for n in numbers if n), sum(1 for s in strings if s)))


main()
