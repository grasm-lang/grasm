"""Writes `packages/qrcode/src/tables.gr` from the QR specification's tables.

ISO/IEC 18004 carries four tables that cannot be derived from anything: how a
symbol of each version and error level is split into blocks, where the
alignment patterns go, and the two BCH-encoded bit patterns for the format and
version information. Between them that is about 400 numbers, and a number
typed wrong in any of them produces a symbol that scans as something else or
does not scan at all.

So they are generated rather than transcribed, the way
`scripts/casefold_table.py` generates its fold table. The source is `segno`,
a pure-Python QR implementation whose own tables come from the standard.

    scripts/qr_tables.py       # rewrite packages/qrcode/src/tables.gr

Run it in the virtual environment that has `segno` installed. The gate
`scripts/qr_diff.sh` re-derives the tables and compares whole matrices, so a
table that drifts is caught rather than trusted.
"""

import os
import sys

try:
    import segno.consts as consts
except ImportError:  # pragma: no cover - the generator needs its source
    sys.exit("segno is not installed; this script only rewrites a generated file")

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, "packages", "qrcode", "src", "main.gr")
BEGIN = "// <<< generated by scripts/qr_tables.py — do not edit below >>>"
END = "// <<< end generated >>>"

# The order this package uses: L, M, Q, H. segno numbers them differently.
LEVELS = [consts.ERROR_LEVEL_L, consts.ERROR_LEVEL_M,
          consts.ERROR_LEVEL_Q, consts.ERROR_LEVEL_H]
MAX_VERSION = 40


def wrap(values, indent="    ", width=78):
    lines, current = [], indent
    for i, v in enumerate(values):
        piece = str(v) + ("," if i < len(values) - 1 else "")
        if len(current) + len(piece) + 1 > width and current.strip():
            lines.append(current.rstrip())
            current = indent
        current += piece + " "
    if current.strip():
        lines.append(current.rstrip())
    return "\n".join(lines)


def main():
    # Blocks, flat: for each version 1..40 and each level L,M,Q,H, four
    # numbers — short block count, short data words, long block count, long
    # data words — plus the error words per block, which is the same for
    # every block of a symbol.
    blocks = []
    for version in range(1, MAX_VERSION + 1):
        for level in LEVELS:
            groups = consts.ECC[version][level]
            first = groups[0]
            second = groups[1] if len(groups) > 1 else None
            ec_per_block = first.num_total - first.num_data
            blocks.extend([
                first.num_blocks, first.num_data,
                second.num_blocks if second else 0,
                second.num_data if second else 0,
                ec_per_block,
            ])

    # Alignment centres. Flat, with a count in front of each version's run.
    alignment = []
    for version in range(1, MAX_VERSION + 1):
        pos = list(consts.ALIGNMENT_POS[version - 2]) if version >= 2 else []
        row = ([6] + pos) if pos else []
        alignment.append(len(row))
        alignment.extend(row)

    # Format information: 15 bits for each (level, mask). segno's order is
    # its own level numbering, so it is rewritten into L,M,Q,H order here.
    format_info = []
    for level in LEVELS:
        for mask in range(8):
            format_info.append(consts.FORMAT_INFO[level * 8 + mask])

    # Version information: 18 bits, versions 7..40.
    version_info = [consts.VERSION_INFO[v - 7] for v in range(7, MAX_VERSION + 1)]

    body = f"""{BEGIN}

/// Five numbers per (version, level), in L, M, Q, H order: how many blocks of
/// the short size, how many data words in one, the same pair for the long
/// size, and the error words every block carries.
let QR_BLOCKS = [
{wrap(blocks)}
]

/// Alignment-pattern centres: a count, then that many coordinates, per
/// version. Version 1 has none, which is why its count is 0.
let QR_ALIGNMENT = [
{wrap(alignment)}
]

/// The 15-bit format information for each of the four levels and eight masks,
/// already BCH-encoded and XORed with the standard's mask pattern.
let QR_FORMAT_INFO = [
{wrap(format_info)}
]

/// The 18-bit version information, for versions 7 to 40. Below 7 a symbol
/// carries none: its size alone identifies it.
let QR_VERSION_INFO = [
{wrap(version_info)}
]

{END}"""

    existing = open(OUT).read()
    if BEGIN not in existing or END not in existing:
        sys.exit(f"{OUT} has no generated region; add the markers first")
    head = existing[:existing.index(BEGIN)]
    tail = existing[existing.index(END) + len(END):]
    with open(OUT, "w") as f:
        f.write(head + body + tail)
    print(f"wrote the tables into {os.path.relpath(OUT, ROOT)}: "
          f"{len(blocks)} block numbers, {len(alignment)} alignment, "
          f"{len(format_info)} format, {len(version_info)} version")


if __name__ == "__main__":
    main()
