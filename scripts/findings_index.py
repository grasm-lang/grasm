#!/usr/bin/env python3
"""Generates ProjectGold/FINDINGS.md's index from its own headings.

A heading reads

    ## F37 — a recorded `()` came back as `0` on another engine (S1, replay) — **fixed**

and carries three things a reader scanning for one entry wants: what it was,
how bad it was, and whether it is closed. Splitting them out is mechanical, so
it is done mechanically.
"""
import re
import sys

PATH = "ProjectGold/FINDINGS.md"
BEGIN = "<!-- index: generated by scripts/findings_index.sh -->"
END = "<!-- end index -->"
HEAD = re.compile(r"^## (F\d+) — (.*)$", re.M)


def split(rest):
    """`what (severity) — status` → the three parts, any of which may be absent."""
    status = ""
    m = re.search(r"\s+—\s+(\*\*.*\*\*|WITHDRAWN.*)$", rest)
    if m:
        status = m.group(1)
        rest = rest[: m.start()]
    sev = ""
    m = re.search(r"\s*\((S\d[^)]*)\)\s*$", rest)
    if m:
        sev = m.group(1)
        rest = rest[: m.start()]
    return rest.strip(), sev or "—", status or "—"


def build(text):
    rows = ["| | what | severity | status |", "|---|---|---|---|"]
    for fid, rest in HEAD.findall(text):
        what, sev, status = split(rest)
        rows.append(f"| [{fid}](#{fid.lower()}) | {what} | {sev} | {status} |")
    return BEGIN + "\n\n" + "\n".join(rows) + "\n\n" + END


def main():
    text = open(PATH).read()
    index = build(text)
    if BEGIN in text and END in text:
        head, rest = text.split(BEGIN, 1)
        _, tail = rest.split(END, 1)
        updated = head + index + tail
    else:
        at = text.index("\n## F")
        updated = text[:at] + "\n" + index + text[at:]

    if "--check" in sys.argv:
        if updated == text:
            print(f"the findings index is current ({len(HEAD.findall(text))} entries)")
            return 0
        print("the findings index is out of date — run scripts/findings_index.sh")
        return 1
    open(PATH, "w").write(updated)
    print(f"wrote {len(HEAD.findall(text))} entries into {PATH}")
    return 0


sys.exit(main())
