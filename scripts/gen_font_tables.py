"""Generate the constant tables of B38's font packages.

- `posttable`'s 258 standard Macintosh glyph names come from
  fontTools.ttLib.standardGlyphOrder.
- `otfname`'s Mac Roman decoding (bytes 128 to 255 as code points) comes
  from Python's `mac_roman` codec.

Each goes below a marker line at the end of its package; with --check
nothing is written and the exit status says whether they are current.
"""
import os
import sys

from fontTools.ttLib import standardGlyphOrder

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
MARKER = "// --- Generated by scripts/gen_font_tables.py; do not edit below this line. ---"


def names_table(names):
    lines = ["let STANDARD_NAMES = ["]
    row = []
    for n in names:
        item = '"' + n + '"'
        if sum(len(x) + 2 for x in row) + len(item) > 100:
            lines.append("    " + ", ".join(row) + ",")
            row = []
        row.append(item)
    lines.append("    " + ", ".join(row) + ",")
    lines.append("]")
    return "\n".join(lines)


def ints_table(name, values):
    lines = [f"let {name} = ["]
    for i in range(0, len(values), 16):
        lines.append("    " + ", ".join(str(v) for v in values[i:i + 16]) + ",")
    lines.append("]")
    return "\n".join(lines)


def tables():
    return {
        "posttable": names_table(standardGlyphOrder.standardGlyphOrder),
        "otfname": ints_table("MAC_ROMAN_HIGH", [ord(c) for c in bytes(range(128, 256)).decode("mac_roman")]),
    }


def main():
    check = "--check" in sys.argv
    stale = []
    for pkg, body in tables().items():
        path = os.path.join(ROOT, "packages", pkg, "src", "main.gr")
        src = open(path).read()
        head = src.split(MARKER)[0].rstrip("\n")
        new = f"{head}\n\n{MARKER}\n\n{body}\n"
        if new != src:
            stale.append(pkg)
            if not check:
                open(path, "w").write(new)
    if check and stale:
        print("stale tables:", " ".join(stale)); sys.exit(1)
    print("tables current" if check else f"wrote: {' '.join(stale) or 'nothing'}")


if __name__ == "__main__":
    main()
