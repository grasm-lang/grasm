"""Write the elliptic-curve parameters OpenSSL knows into packages/ecc.

Each curve's prime, coefficients, base point and order come from
`openssl ecparam -param_enc explicit -text`, not from a standard typed out by
hand, and are regenerated rather than edited:

    python3 scripts/gen_curves.py packages/ecc/src/main.gr
    python3 scripts/gen_curves.py --check packages/ecc/src/main.gr

The parameters replace whatever is between the `BEGIN GENERATED` and
`END GENERATED` lines of the file.
"""
import re
import subprocess
import sys

# Grasm's name for each curve, then OpenSSL's.
CURVES = [("P-256", "prime256v1"), ("P-384", "secp384r1"),
          ("P-521", "secp521r1"), ("secp256k1", "secp256k1"),
          ("brainpoolP256r1", "brainpoolP256r1"),
          ("brainpoolP384r1", "brainpoolP384r1"),
          ("brainpoolP512r1", "brainpoolP512r1"), ("SM2", "SM2")]


def params(openssl_name):
    text = subprocess.run(["openssl", "ecparam", "-name", openssl_name,
                           "-param_enc", "explicit", "-text", "-noout"],
                          capture_output=True, text=True, check=True).stdout
    fields = {}
    current = None
    for line in text.splitlines():
        head = re.match(r"^(\w[\w ()]*):\s*(.*)$", line)
        if head and not line.startswith(" "):
            current = head.group(1).strip()
            rest = head.group(2).strip()
            fields[current] = rest
            continue
        if current:
            fields[current] += line.strip()

    def num(key):
        raw = fields[key].replace(":", "").strip()
        m = re.match(r"^(\d+)\s*\(0x([0-9a-f]+)\)$", raw)
        if m:
            return int(m.group(2), 16)
        return int(raw or "0", 16)

    gen = fields["Generator (uncompressed)"].replace(":", "")
    gen = bytes.fromhex(gen)
    assert gen[0] == 4
    half = (len(gen) - 1) // 2
    cofactor = num("Cofactor")
    assert cofactor == 1, openssl_name
    return [num("Prime"), num("A"), num("B"),
            int.from_bytes(gen[1:1 + half], "big"),
            int.from_bytes(gen[1 + half:], "big"), num("Order")]


def block():
    version = subprocess.run(["openssl", "version"], capture_output=True,
                             text=True).stdout.split()[1]
    rows = []
    for name, ossl in CURVES:
        rows.append(name + "|" + "|".join(f"{v:x}" for v in params(ossl)))
    lines = [f"// BEGIN GENERATED by scripts/gen_curves.py from OpenSSL {version}",
             "let EC_PARAMS_PACKED = \"\" +"]
    for i, row in enumerate(rows):
        tail = " +" if i + 1 < len(rows) else ""
        sep = ";" if i + 1 < len(rows) else ""
        lines.append(f"\"{row}{sep}\"{tail}")
    return "\n".join(lines) + "\n"


def main():
    check = sys.argv[1] == "--check"
    path = sys.argv[-1]
    source = open(path, encoding="utf-8").read()
    begin = source.index("// BEGIN GENERATED")
    end = source.index("// END GENERATED")
    updated = source[:begin] + block() + source[end:]
    if check:
        # The header names the OpenSSL that produced the table. The curves are
        # fixed by their standards and do not change between releases, so a
        # different version is not staleness: when Homebrew moved openssl from
        # 3.6.3 to 4.0.3 this check failed pubkeydiff over that one word.
        # Compare everything but the version.
        def unversioned(text):
            return re.sub(r"(// BEGIN GENERATED by scripts/gen_curves\.py from OpenSSL )\S+", r"\1*", text)
        if unversioned(updated) != unversioned(source):
            print(f"{path} is stale: run python3 scripts/gen_curves.py {path}")
            sys.exit(1)
        return
    open(path, "w", encoding="utf-8").write(updated)
    print(f"{len(CURVES)} curves")


main()
