"""Write the code points Python's `repr` escapes into a package.

`repr` of a str escapes every character `str.isprintable()` is false for,
and whether a character is printable depends on the Unicode database of the
Python that answers — so the table is read from that Python rather than
typed, and regenerated when it changes:

    python3 scripts/gen_printable.py packages/pyliteral/src/main.gr

The ranges replace whatever is between the `BEGIN GENERATED` and
`END GENERATED` lines of the file.
"""
import sys
import unicodedata


def ranges():
    out, start = [], None
    for cp in range(0x110000):
        hidden = not chr(cp).isprintable()
        if hidden and start is None:
            start = cp
        if not hidden and start is not None:
            out.append((start, cp - 1))
            start = None
    if start is not None:
        out.append((start, 0x10FFFF))
    return out


def main():
    path = sys.argv[1]
    source = open(path, encoding="utf-8").read()
    begin = source.index("// BEGIN GENERATED")
    end = source.index("// END GENERATED")
    packed = ",".join(f"{a:x}-{b:x}" for a, b in ranges())
    lines = [f"// BEGIN GENERATED by scripts/gen_printable.py from Python's "
             f"Unicode {unicodedata.unidata_version}"]
    lines.append("let HIDDEN_PACKED = \"\" +")
    chunk = 64
    pieces = [packed[i:i + chunk] for i in range(0, len(packed), chunk)]
    for i, piece in enumerate(pieces):
        tail = " +" if i + 1 < len(pieces) else ""
        lines.append(f"\"{piece}\"{tail}")
    block = "\n".join(lines) + "\n"
    open(path, "w", encoding="utf-8").write(source[:begin] + block +
                                            source[end:])
    print(f"{len(ranges())} ranges of code points repr escapes")


main()
