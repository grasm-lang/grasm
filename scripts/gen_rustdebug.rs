// Writes the code points Rust's `{:?}` of a string escapes into
// compiler/front/src/rdebug.gr.
//
// `grasm tokens` and `grasm ast` print strings with Rust's `Debug`, which
// writes a character as `\u{...}` when the standard library's own tables call
// it unprintable or grapheme-extending. Those tables are the Unicode version
// of the Rust that built `grasm`, so they are read from that Rust rather than
// typed, and regenerated when it changes:
//
//     rustc -O -o "$SCRATCH/gen_rustdebug" scripts/gen_rustdebug.rs
//     "$SCRATCH/gen_rustdebug" compiler/front/src/rdebug.gr
//
// The ranges replace whatever is between the `BEGIN GENERATED` and
// `END GENERATED` lines of the file. With `-check` nothing is written and the
// exit status says whether the file is current.
//
// Every escaped character is checked to be escaped as the Grasm side writes
// it: the six named escapes, or `\u{` lowercase hex `}`.
use std::process::exit;

fn named(c: char) -> Option<&'static str> {
    Some(match c {
        '\0' => "\\0",
        '\t' => "\\t",
        '\r' => "\\r",
        '\n' => "\\n",
        '\\' => "\\\\",
        '"' => "\\\"",
        _ => return None,
    })
}

fn main() {
    let args: Vec<String> = std::env::args().collect();
    let check = args.iter().any(|a| a == "-check");
    let Some(path) = args.iter().skip(1).find(|a| *a != "-check") else {
        eprintln!("usage: gen_rustdebug [-check] <file.gr>");
        exit(2);
    };
    let mut ranges: Vec<(u32, u32)> = Vec::new();
    let mut open: Option<u32> = None;
    for cp in 0..=0x10FFFFu32 {
        let escaped = match char::from_u32(cp) {
            None => false,
            Some(c) => {
                let s = c.to_string();
                let dbg = format!("{s:?}");
                let inner = &dbg[1..dbg.len() - 1];
                if inner == s {
                    false
                } else {
                    let want = named(c)
                        .map(str::to_string)
                        .unwrap_or_else(|| format!("\\u{{{cp:x}}}"));
                    if inner != want {
                        eprintln!("U+{cp:04X} is escaped as {inner}, not {want}");
                        exit(1);
                    }
                    named(c).is_none()
                }
            }
        };
        match (escaped, open) {
            (true, None) => open = Some(cp),
            (false, Some(a)) => {
                ranges.push((a, cp - 1));
                open = None;
            }
            _ => {}
        }
    }
    if let Some(a) = open {
        ranges.push((a, 0x10FFFF));
    }
    let packed = ranges
        .iter()
        .map(|(a, b)| format!("{a:x}-{b:x}"))
        .collect::<Vec<_>>()
        .join(",");
    let mut lines = vec![format!(
        "// BEGIN GENERATED by scripts/gen_rustdebug.rs from rustc {}",
        option_env!("RUSTC_VERSION_FOR_TABLE").unwrap_or("(see the commit)")
    )];
    lines.push("pub fn escaped_packed() -> str {".to_string());
    lines.push("    \"\" +".to_string());
    let bytes = packed.as_bytes();
    let mut i = 0;
    while i < bytes.len() {
        let end = (i + 64).min(bytes.len());
        let tail = if end == bytes.len() { "" } else { " +" };
        lines.push(format!("    \"{}\"{tail}", &packed[i..end]));
        i = end;
    }
    lines.push("}".to_string());
    let block = lines.join("\n") + "\n";
    let source = std::fs::read_to_string(path).unwrap_or_else(|e| {
        eprintln!("cannot read {path}: {e}");
        exit(2)
    });
    let (Some(begin), Some(end)) = (
        source.find("// BEGIN GENERATED"),
        source.find("// END GENERATED"),
    ) else {
        eprintln!("{path} has no BEGIN/END GENERATED markers");
        exit(2);
    };
    let out = format!("{}{}{}", &source[..begin], block, &source[end..]);
    if check {
        if out != source {
            eprintln!("{path} is not what this rustc generates");
            exit(1);
        }
        println!("{path} is current: {} ranges", ranges.len());
        return;
    }
    std::fs::write(path, out).unwrap_or_else(|e| {
        eprintln!("cannot write {path}: {e}");
        exit(2)
    });
    println!("{} ranges of code points Rust's Debug escapes", ranges.len());
}
