"""Write the label table of `packages/htmlcharset` from x/text's.

x/text generates `encoding/htmlindex/tables.go` from the WHATWG Encoding
Standard; the Go oracle asks `htmlindex` what each label there means, and
this writes the answers below the package's marker.

    python3 scripts/gen_htmlcharset.py           # rewrite the table
    python3 scripts/gen_htmlcharset.py --check   # fail if it is stale
"""
import glob
import json
import os
import subprocess
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(ROOT, "scripts/lib/gomods"))
import oracle  # noqa: E402

MARKER = "// ---- Generated by scripts/gen_htmlcharset.py from x/text's label table. Do not edit below. ----"
PATH = os.path.join(ROOT, "packages/htmlcharset/src/main.gr")


def table(go):
    cache = subprocess.run(["go", "env", "GOMODCACHE"], capture_output=True, text=True).stdout.strip()
    tables = sorted(glob.glob(os.path.join(cache, "golang.org/x/text@v0.43.0/encoding/htmlindex/tables.go")))[-1]
    out = subprocess.run([go], input=json.dumps([{"op": "labels", "args": [tables]}]), capture_output=True, text=True, check=True)
    return json.loads(out.stdout)[0].split(" ")


def render(entries):
    lines, line = [], ""
    for e in entries:
        if line and len(line) + 1 + len(e) > 72:
            lines.append(line)
            line = e
        else:
            line = (line + " " + e) if line else e
    lines.append(line)
    body = ["fn packed_labels() -> str {", f'    return "{lines[0]} "' + (" +" if len(lines) > 1 else "")]
    for i, piece in enumerate(lines[1:]):
        body.append(f'    "{piece} "' + (" +" if i < len(lines) - 2 else ""))
    return "\n".join(body + ["}", ""])


def main():
    import tempfile
    go = oracle.build(os.path.join(tempfile.mkdtemp(), "gomods"))
    entries = table(go)
    current = open(PATH).read()
    new = current.split(MARKER)[0] + MARKER + "\n" + render(entries)
    print(f"htmlcharset: {len(entries)} labels, {len(set(e.split('=')[1] for e in entries))} encodings")
    if "--check" in sys.argv:
        if new != current:
            print(f"{PATH} is stale; run python3 scripts/gen_htmlcharset.py")
            sys.exit(1)
    else:
        open(PATH, "w").write(new)


if __name__ == "__main__":
    main()
