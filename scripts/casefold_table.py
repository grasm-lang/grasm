"""Writes `packages/casefold/src/main.gr`'s fold tables from Unicode itself.

The first version of this package carried hand-written range rules — "Latin
Extended-A is laid out in pairs, so even code points fold to the next one".
Those rules are *almost* right, and a sweep against a real implementation
found two kinds of failure they cannot avoid: characters folded that should
not have been (`ŋ` mapped up to `Ŋ`, because the parity of that block flips
partway through), and roughly four hundred that fold and were missed.

So the tables are generated, the way `scripts/site_highlight.py` reads the
keyword list out of the lexer rather than restating it. What is derived here
cannot drift from what Python's `str.casefold` does, and Python's is the
Unicode `CaseFolding.txt` full mapping.

    scripts/casefold_table.py        # rewrite packages/casefold/src/main.gr

Every mapping that changes exactly one code point becomes a run of
`(start, end, step, delta)`; 1,453 of them compress to 200 runs. The 104
mappings that produce more than one character -- `ß` to `ss`, the ligatures,
the Greek forms that decompose -- are a sorted table searched the same way.
"""

import os
import unicodedata

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, "packages", "casefold", "src", "main.gr")

HEADER = '''// Comparing text without caring about case, which `to_lower` does not do.
//
// `a.to_lower() == b.to_lower()` is the usual attempt and it is wrong in ways
// that matter:
//
//   - German "ß" lowercases to itself, so "STRASSE" and "straße" compare
//     unequal even though they are the same word. Case *folding* maps ß to
//     "ss", which is why folding can make a string longer and lowercasing
//     never can.
//   - Greek final sigma "ς" and medial "σ" are the same letter in different
//     positions, and the capitals carrying a tonos lowercase into a different
//     block entirely, so no offset rule reaches them.
//   - A ligature "ﬁ" is one character that lowercases to itself and folds to
//     "fi".
//
// The tables below are generated by `scripts/casefold_table.py` from the
// Unicode full case-folding mapping, and cover every code point that folds:
// {simple} that fold to a single character, compressed into {runs} runs, and
// {special} that fold to more than one.
//
// They are generated because the hand-written version of this file was wrong.
// Its rules read like the block layouts they describe — "Latin Extended-A is
// laid out in pairs" — and a sweep against a real implementation found both
// kinds of error those rules produce: 35 characters folded that should not
// have been, `ŋ` mapping *up* to `Ŋ` because that block's parity flips
// partway through, and 445 missed.
'''

FOOTER = '''
/// The delta for `code`, or 0 when it folds to itself.
///
/// Runs are sorted, so this is a bisection: eight comparisons over the whole
/// of Unicode rather than two hundred.
fn simple_delta(code: i64) -> i64 {
    let runs = FOLD_RUNS
    var lo = 0
    var hi = runs.len() / 4 - 1
    while lo <= hi {
        let mid = (lo + hi) / 2
        let at = mid * 4
        if code < runs[at] {
            hi = mid - 1
            continue
        }
        if code > runs[at + 1] {
            lo = mid + 1
            continue
        }
        // Inside the run's span, but the run may skip alternate values.
        if (code - runs[at]) % runs[at + 2] != 0 {
            return 0
        }
        return runs[at + 3]
    }
    return 0
}

/// The index of `code` in the multi-character table, or -1.
fn special_at(code: i64) -> i64 {
    let codes = FOLD_SPECIAL_CODE
    var lo = 0
    var hi = codes.len() - 1
    while lo <= hi {
        let mid = (lo + hi) / 2
        if codes[mid] == code {
            return mid
        }
        if codes[mid] < code {
            lo = mid + 1
        } else {
            hi = mid - 1
        }
    }
    return 0 - 1
}

/// One code point folded to one code point, where such a mapping exists.
///
/// A character whose folded form is more than one code point comes back
/// unchanged here — `fold` is the function that handles those.
pub fn fold_code(code: i64) -> i64 {
    return code + simple_delta(code)
}

/// The folded form of a string. May be longer than what went in.
pub fn fold(text: str) -> str {
    var out = ""
    for code in text.codes() {
        let at = special_at(code)
        if at >= 0 {
            out = out + FOLD_SPECIAL_TEXT[at]
        } else {
            out = out + (code + simple_delta(code)).to_char()
        }
    }
    return out
}

/// The comparison this package exists for.
pub fn equal(a: str, b: str) -> bool {
    return fold(a) == fold(b)
}

/// Ordering by folded form, with the original as the tie-break so that two
/// strings differing only in case still have a stable order.
pub fn compare(a: str, b: str) -> i64 {
    let fa = fold(a)
    let fb = fold(b)
    if fa < fb {
        return 0 - 1
    }
    if fa > fb {
        return 1
    }
    if a < b {
        return 0 - 1
    }
    if a > b {
        return 1
    }
    return 0
}

pub fn contains(haystack: str, needle: str) -> bool {
    return fold(haystack).contains(fold(needle))
}

pub fn starts_with(text: str, prefix: str) -> bool {
    return fold(text).starts_with(fold(prefix))
}

pub fn ends_with(text: str, suffix: str) -> bool {
    return fold(text).ends_with(fold(suffix))
}

pub fn index_of(haystack: str, needle: str) -> Option[i64] {
    // The offset is into the *folded* text, because folding can change the
    // length and an offset into the original would be a guess.
    return fold(haystack).index_of(fold(needle))
}

/// Whether folding this string changes its length — the case `to_lower`
/// cannot handle at all.
pub fn changes_length(text: str) -> bool {
    return fold(text).len() != text.len()
}

/// Whether folding changes the string in any way.
pub fn is_folded(text: str) -> bool {
    return fold(text) == text
}

/// Deduplicate a list caselessly, keeping the first spelling of each.
pub fn unique(items: [str]) -> [str] {
    var seen: [str] = []
    var out: [str] = []
    for item in items {
        let key = fold(item)
        if not seen.contains(key) {
            seen.push(key)
            out.push(item)
        }
    }
    return out
}

/// How many code points the tables cover, so a test can assert the generated
/// file is the generated file.
pub fn run_count() -> i64 {
    return FOLD_RUNS.len() / 4
}

pub fn special_count() -> i64 {
    return FOLD_SPECIAL_CODE.len()
}
'''


def wrap_ints(values, indent="    ", width=78):
    lines = []
    current = indent
    for i, v in enumerate(values):
        piece = str(v) + ("," if i < len(values) - 1 else "")
        if len(current) + len(piece) + 1 > width and current.strip():
            lines.append(current.rstrip())
            current = indent
        current += piece + " "
    if current.strip():
        lines.append(current.rstrip())
    return "\n".join(lines)


def gr_string(text):
    out = '"'
    for ch in text:
        code = ord(ch)
        if ch == '"':
            out += '\\"'
        elif ch == "\\":
            out += "\\\\"
        elif code < 0x20 or code == 0x7F or unicodedata.category(ch) in ("Cf", "Mn"):
            # Combining and format characters are written as escapes: one of
            # them sitting bare in the source is invisible in every editor.
            out += "\\u{%04x}" % code
        else:
            out += ch
    return out + '"'


def main():
    simple = {}
    special = {}
    for c in range(0x110000):
        if 0xD800 <= c <= 0xDFFF:
            continue
        ch = chr(c)
        f = ch.casefold()
        if f == ch:
            continue
        if len(f) == 1:
            simple[c] = ord(f) - c
        else:
            special[c] = f

    codes = sorted(simple)
    runs = []
    i = 0
    while i < len(codes):
        c = codes[i]
        delta = simple[c]
        best = (0, 1)
        for step in (1, 2):
            n = 1
            while (i + n < len(codes) and codes[i + n] == c + step * n
                   and simple[codes[i + n]] == delta):
                n += 1
            if n > best[0]:
                best = (n, step)
        n, step = best
        runs.append((c, c + step * (n - 1), step, delta))
        i += n

    flat = [v for run in runs for v in run]
    special_codes = sorted(special)

    body = [HEADER.format(simple=len(simple), runs=len(runs), special=len(special))]
    body.append("")
    body.append("/// Runs of four: first code point, last, step, and what to add.")
    body.append("let FOLD_RUNS = [")
    body.append(wrap_ints(flat))
    body.append("]")
    body.append("")
    body.append("/// Code points whose folded form is more than one character, sorted.")
    body.append("let FOLD_SPECIAL_CODE = [")
    body.append(wrap_ints(special_codes))
    body.append("]")
    body.append("")
    body.append("/// What each of those folds to, in the same order.")
    body.append("let FOLD_SPECIAL_TEXT = [")
    body.append(wrap_ints([gr_string(special[c]) for c in special_codes]))
    body.append("]")
    body.append(FOOTER)

    with open(OUT, "w") as f:
        f.write("\n".join(body))
    print(f"wrote {os.path.relpath(OUT, ROOT)}: "
          f"{len(runs)} runs, {len(special_codes)} special")


if __name__ == "__main__":
    main()
