"""Writes the case-insensitive matching tables at the end of
pystrptime/src/main.gr from the Python running it, which must be CPython
3.13: `re`'s own simple lowercase (_sre.unicode_tolower), which characters
it counts as cased (_sre.unicode_iscased), and its extra case equivalents
(re._casefix._EXTRA_CASES). b57_diff.py runs this and fails when the
committed table differs."""
import _sre
import re._casefix
import sys

assert sys.version_info[:2] == (3, 13), sys.version


def runs_of(pairs):
    """(code point, delta) pairs as runs: first, last, step, delta."""
    out = []
    k = 0
    while k < len(pairs):
        cp, d = pairs[k]
        last, step = cp, 1
        if k + 1 < len(pairs) and pairs[k + 1][1] == d and pairs[k + 1][0] - cp in (1, 2):
            step = pairs[k + 1][0] - cp
            j = k + 1
            while j < len(pairs) and pairs[j][1] == d and pairs[j][0] == last + step:
                last = pairs[j][0]
                j += 1
            k = j
        else:
            k += 1
        out += [cp, last, step, d]
    return out


lower = []
cased_starts, last = [], None
for cp in range(0x110000):
    lo = _sre.unicode_tolower(cp)
    if lo != cp:
        lower.append((cp, lo - cp))
    c = bool(_sre.unicode_iscased(cp))
    if c != last:
        cased_starts.append(cp)
        last = c
extra = []
for k in sorted(re._casefix._EXTRA_CASES):
    v = re._casefix._EXTRA_CASES[k]
    assert len(v) <= 2
    extra += [k, len(v)] + list(v) + [0] * (2 - len(v))
lines = ["", "// Generated by gen_tables.py from CPython 3.13's re module (_sre.unicode_tolower,", "// _sre.unicode_iscased, re._casefix). Do not edit: regenerate.", "",
         "/// re's simple lowercase: first, last, step and delta.", "pub let PYSTRPTIME_LOWER_RUNS: [i64] = [" + ", ".join(map(str, runs_of(lower))) + "]", "",
         "/// Where re's cased flag changes, starting with not cased at 0.", "pub let PYSTRPTIME_CASED_STARTS: [i64] = [" + ", ".join(map(str, cased_starts)) + "]", "",
         "/// re._casefix: a lowercase code point, how many extra equivalents, and up to two.",
         "pub let PYSTRPTIME_EXTRA_CASES: [i64] = [" + ", ".join(map(str, extra)) + "]", ""]
sys.stdout.write("\n".join(lines))
