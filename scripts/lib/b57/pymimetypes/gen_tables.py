"""Writes the tables at the end of pymimetypes/src/main.gr from the Python
running it, which must be CPython 3.13: mimetypes' built-in defaults, in
their dict order. b57_diff.py runs this and fails when the committed
table differs."""
import mimetypes
import sys

assert sys.version_info[:2] == (3, 13), sys.version


def strs(name, items):
    return f"pub let {name}: [str] = [" + ", ".join('"' + x + '"' for x in items) + "]"


def pairs(d):
    out = []
    for k, v in d.items():
        assert '"' not in k + v and "\\" not in k + v and "{" not in k + v
        out += [k, v]
    return out


lines = ["", "// Generated by gen_tables.py from CPython 3.13's mimetypes defaults. Do not", "// edit: regenerate.", "",
         "/// `_types_map_default`: extension, type; in dict order.", strs("PYMIME_TYPES", pairs(mimetypes._types_map_default)), "",
         "/// `_common_types_default` (non-strict).", strs("PYMIME_COMMON", pairs(mimetypes._common_types_default)), "",
         "/// `_encodings_map_default`.", strs("PYMIME_ENCODINGS", pairs(mimetypes._encodings_map_default)), "",
         "/// `_suffix_map_default`.", strs("PYMIME_SUFFIXES", pairs(mimetypes._suffix_map_default)), ""]
sys.stdout.write("\n".join(lines))
