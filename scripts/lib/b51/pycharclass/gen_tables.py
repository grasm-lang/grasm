"""Writes packages/pycharclass/src/tables.gr from the Python running it,
which must be CPython 3.13 (Unicode 15.1). scripts/b51_diff.py runs it
and fails when the committed table differs."""
import sys
import unicodedata

CATS = ["Lu", "Ll", "Lt", "Lm", "Lo", "Mn", "Mc", "Me", "Nd", "Nl", "No", "Pc", "Pd", "Ps", "Pe", "Pi", "Pf", "Po", "Sm", "Sc", "Sk", "So", "Zs", "Zl",
        "Zp", "Cc", "Cf", "Cs", "Co", "Cn"]


def code(cp):
    c = chr(cp)
    flags = 0
    for bit, test in enumerate([c.isalpha(), c.isdecimal(), c.isdigit(), c.isnumeric(), c.isspace(), c.isprintable(), c.isupper(), c.islower(),
                                unicodedata.category(c) == "Lt", c.isidentifier(), ("a" + c).isidentifier()]):
        if test:
            flags |= 1 << bit
    return CATS.index(unicodedata.category(c)) * 2048 + flags


def main():
    assert unicodedata.unidata_version == "15.1.0", unicodedata.unidata_version
    starts, values = [], []
    last = None
    for cp in range(0x110000):
        v = code(cp)
        if v != last:
            starts.append(cp)
            values.append(v)
            last = v
    out = ["// Generated by scripts/lib/b51/pycharclass/gen_tables.py from CPython 3.13's",
           "// unicodedata (Unicode 15.1.0). Do not edit: regenerate.", "",
           "/// Where each run of code points with the same class begins.",
           "pub let RUN_STARTS: [i64] = [" + ", ".join(map(str, starts)) + "]", "",
           "/// Each run's general category (its index in CATEGORY_NAMES) times 2048,",
           "/// plus the flags.", "pub let RUN_VALUES: [i64] = [" + ", ".join(map(str, values)) + "]", ""]
    sys.stdout.write("\n".join(out))
    print(f"{len(starts)} runs", file=sys.stderr)


main()
