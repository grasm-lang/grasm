// Generates the Unicode tables pk/nodematchesglob uses, from the Node that
// is its oracle (Node 25, Unicode 17), and checks each against V8's own
// regular expressions. Usage: node gen_tables.js CaseFolding-17.0.0.txt
'use strict';
const fs = require('fs');
const b36 = (n) => n.toString(36);

// General categories minimatch's posix classes name.
const CATS = ['L', 'Nl', 'Nd', 'Zs', 'Cc', 'Z', 'C', 'Ll', 'P', 'Lu', 'Pc'];
const sets = {};
for (const cat of CATS) {
  const re = new RegExp('^\\p{' + cat + '}$', 'u');
  const ranges = [];
  let start = -1;
  for (let cp = 0; cp <= 0x110000; cp++) {
    const inSet = cp <= 0x10ffff && re.test(String.fromCodePoint(cp));
    if (inSet && start < 0) start = cp;
    if (!inSet && start >= 0) { ranges.push([start, cp - 1]); start = -1; }
  }
  let prev = 0;
  const out = [];
  for (const [a, b] of ranges) { out.push(b36(a - prev), b36(b - a + 1)); prev = b + 1; }
  sets[cat] = out.join('.');
}

// Canonicalize without the u flag: toUpperCase, kept only when it is one
// code unit and does not turn a non-ASCII unit into an ASCII one.
const canonNonU = (x) => {
  const u = String.fromCharCode(x).toUpperCase();
  if (u.length !== 1) return x;
  const cu = u.charCodeAt(0);
  if (x >= 128 && cu < 128) return x;
  return cu;
};
// Simple case folding (statuses C and S) with the u flag.
const scfMap = new Map();
for (const line of fs.readFileSync(process.argv[2], 'utf8').split('\n')) {
  const m = /^([0-9A-F]+); ([CS]); ([0-9A-F]+);/.exec(line);
  if (m) scfMap.set(parseInt(m[1], 16), parseInt(m[3], 16));
}
const scf = (x) => scfMap.has(x) ? scfMap.get(x) : x;

const encodeMap = (pairs) => {
  let prev = 0;
  const out = [];
  for (const [x, y] of pairs) { out.push(b36(x - prev), (y < x ? '-' : '') + b36(Math.abs(y - x))); prev = x; }
  return out.join('.');
};
const nonU = [];
for (let x = 0; x < 0x10000; x++) if (canonNonU(x) !== x) nonU.push([x, canonNonU(x)]);
const uPairs = [...scfMap.entries()].sort((a, b) => a[0] - b[0]);

// Check both against V8: every pair related by any case mapping must match
// exactly when the two canonicalize alike.
const related = (x) => {
  const s = String.fromCodePoint(x);
  const r = new Set([x, canonNonU(x < 0x10000 ? x : 0), scf(x)]);
  for (const t of [s.toUpperCase(), s.toLowerCase()]) if ([...t].length === 1) r.add(t.codePointAt(0));
  for (const [a, b] of uPairs) if (b === scf(x)) r.add(a);
  return r;
};
let checked = 0;
const byCanon = new Map();
for (let x = 0; x < 0x10000; x++) { const k = canonNonU(x); if (!byCanon.has(k)) byCanon.set(k, []); byCanon.get(k).push(x); }
for (let x = 0; x < 0x10000; x++) {
  if (x >= 0xd800 && x < 0xe000) continue;
  const re = new RegExp('^\\u' + x.toString(16).padStart(4, '0') + '$', 'i');
  for (const y of new Set([...byCanon.get(canonNonU(x)), ...related(x)])) {
    if (y >= 0x10000 || (y >= 0xd800 && y < 0xe000)) continue;
    if (re.test(String.fromCharCode(y)) !== (canonNonU(x) === canonNonU(y))) throw new Error('non-u mismatch ' + x + ' ' + y);
    checked++;
  }
}
for (const x of new Set([...scfMap.keys(), ...scfMap.values()])) {
  const re = new RegExp('^\\u{' + x.toString(16) + '}$', 'iu');
  for (const y of related(x)) {
    if (re.test(String.fromCodePoint(y)) !== (scf(x) === scf(y))) throw new Error('u mismatch ' + x + ' ' + y);
    checked++;
  }
}
// And code points no folding touches fold only to themselves.
for (let x = 0; x <= 0x10ffff; x += 97) {
  if ((x >= 0xd800 && x < 0xe000) || scfMap.has(x)) continue;
  const s = String.fromCodePoint(x);
  for (const t of [s.toUpperCase(), s.toLowerCase()]) {
    const y = t.codePointAt(0);
    if ([...t].length === 1 && y !== x && scf(y) !== x && new RegExp('^\\u{' + x.toString(16) + '}$', 'iu').test(t)) throw new Error('u unexpected ' + x);
  }
}
process.stderr.write(`checked ${checked} pairs; non-u ${nonU.length} entries, scf ${uPairs.length} entries\n`);

const lines = [];
lines.push('// Generated by b62lib/nodematchesglob/gen_tables.js from Node ' + process.version + ' (Unicode ' + process.versions.unicode + ').');
lines.push('// Do not edit by hand.');
lines.push('');
lines.push('/// Ranges of a general category, as base-36 gaps and lengths.');
lines.push('fn category_table(name: str) -> str {');
for (const cat of CATS) {
  lines.push('    if name == "' + cat + '" {');
  lines.push('        return "' + sets[cat] + '"');
  lines.push('    }');
}
lines.push('    return ""');
lines.push('}');
lines.push('');
lines.push('/// Code units whose case-insensitive form without the u flag differs:');
lines.push('/// base-36 steps from the previous unit, then the signed distance to it.');
lines.push('fn canon_table() -> str {');
lines.push('    return "' + encodeMap(nonU) + '"');
lines.push('}');
lines.push('');
lines.push('/// Simple case folding (CaseFolding.txt statuses C and S), the same way.');
lines.push('fn fold_table() -> str {');
lines.push('    return "' + encodeMap(uPairs) + '"');
lines.push('}');
process.stdout.write(lines.join('\n') + '\n');
