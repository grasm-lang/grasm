"""Writes the case tables at the end of pystr/src/main.gr, from the Python
running it, which must be CPython 3.13 (Unicode 15.1). Also writes
pools.json next to this file: character pools the diff's generator draws
from (it runs under another Python). b56_diff.py runs this and fails when
the committed table differs from what it prints.

Every value comes from Python's own str methods: c.lower(), c.upper() and
c.title() of one character (the full mappings), cased as c.islower() or
c.isupper() or c.istitle(), and case-ignorable read off how lower()
treats a capital sigma next to the character."""
import json
import os
import sys
import unicodedata

assert sys.version_info[:2] == (3, 13) and unicodedata.unidata_version == "15.1.0", sys.version


def chars():
    for cp in range(0x110000):
        if 0xD800 <= cp <= 0xDFFF:
            continue
        yield cp, chr(cp)


def cased(c):
    return c.islower() or c.isupper() or c.istitle()


def ignorable(c):
    if cased(c):
        return ("AΣ" + c).lower()[1] == "ς"
    return ("A" + c + "Σ").lower()[-1] == "ς"


def runs(pairs):
    """Single-character mappings as runs: first, last, step, delta."""
    out = []
    k = 0
    while k < len(pairs):
        cp, d = pairs[k]
        last, step = cp, 1
        if k + 1 < len(pairs) and pairs[k + 1][1] == d and pairs[k + 1][0] - cp in (1, 2):
            step = pairs[k + 1][0] - cp
            j = k + 1
            while j < len(pairs) and pairs[j][1] == d and pairs[j][0] == last + step:
                last = pairs[j][0]
                j += 1
            k = j
        else:
            k += 1
        out += [cp, last, step, d]
    return out


def main():
    single = {0: [], 1: [], 2: []}
    special = []
    props_starts, props_values, last = [], [], None
    pools = {"cased": [], "ignorable": [], "special": [], "upper": [], "lower": [], "title": [], "both": []}
    for cp, c in chars():
        for kind, m in enumerate([c.lower(), c.upper(), c.title()]):
            if m == c:
                continue
            if len(m) == 1:
                single[kind].append((cp, ord(m) - cp))
            else:
                special += [cp * 4 + kind, len(m)] + [ord(x) for x in m] + [0] * (3 - len(m))
                pools["special"].append(cp)
        v = (1 if cased(c) else 0) + (2 if ignorable(c) else 0)
        if v != last:
            props_starts.append(cp)
            props_values.append(v)
            last = v
        if v & 1:
            pools["cased"].append(cp)
        if v & 2:
            pools["ignorable"].append(cp)
        if v == 3:
            pools["both"].append(cp)
        if c.isupper():
            pools["upper"].append(cp)
        if c.islower():
            pools["lower"].append(cp)
        if unicodedata.category(c) == "Lt":
            pools["title"].append(cp)
    out = ["", "// Generated by gen_tables.py from CPython 3.13's str methods (Unicode 15.1.0).", "// Do not edit: regenerate.", ""]
    for name, kind in [("LOWER", 0), ("UPPER", 1), ("TITLE", 2)]:
        out.append(f"/// Single-character {name.lower()} mappings: first, last, step and delta.")
        out.append(f"pub let PYSTR_{name}_RUNS: [i64] = [" + ", ".join(map(str, runs(single[kind]))) + "]")
        out.append("")
    out.append("/// Longer mappings, five numbers each: code point * 4 + kind (0 lower, 1")
    out.append("/// upper, 2 title), length, and up to three code points.")
    out.append("pub let PYSTR_SPECIAL: [i64] = [" + ", ".join(map(str, special)) + "]")
    out.append("")
    out.append("/// Where each run of code points with the same case properties begins,")
    out.append("/// and its value: 1 cased, 2 case-ignorable.")
    out.append("pub let PYSTR_PROP_STARTS: [i64] = [" + ", ".join(map(str, props_starts)) + "]")
    out.append("pub let PYSTR_PROP_VALUES: [i64] = [" + ", ".join(map(str, props_values)) + "]")
    out.append("")
    sys.stdout.write("\n".join(out))
    json.dump(pools, open(os.path.join(os.path.dirname(os.path.abspath(__file__)), "pools.json"), "w"))
    print(f"runs {len(runs(single[0])) // 4} {len(runs(single[1])) // 4} {len(runs(single[2])) // 4}, special {len(special) // 5}, "
          f"props {len(props_starts)}", file=sys.stderr)


main()
