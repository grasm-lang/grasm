# Writes the printable-character table at the end of
# packages/rubyshellwords/src/main.gr from the Ruby running it, which must
# be Ruby 2.6 (Unicode 12.1): the code points String#inspect leaves as
# they are in a UTF-8 string. (Asked of inspect itself: the regexp class
# [[:print:]] disagrees with it, on U+0085 for one.)
Encoding.default_external = Encoding::UTF_8
special = ['"', "\\", "#", "\n", "\r", "\t", "\f", "\v", "\b", "\a", "\e"].map(&:ord)
starts = []
ends = []
inside = false
(0..0x10FFFF).each do |cp|
  s = (0xD800..0xDFFF).cover?(cp) ? nil : [cp].pack("U")
  printable = s && !special.include?(cp) && s.inspect == "\"#{s}\""
  printable ||= special.include?(cp) && cp == "#".ord
  if printable && !inside
    starts << cp
    inside = true
  elsif !printable && inside
    ends << cp
    inside = false
  end
end
ends << 0x110000 if inside
puts "// Generated by scripts/lib/b52/rubyshellwords/gen_tables.rb from Ruby #{RUBY_VERSION}"
puts "// (Unicode #{RbConfig::CONFIG["UNICODE_VERSION"]}). Do not edit: regenerate."
puts ""
puts "/// Where each run of characters Ruby's inspect prints as they are begins."
puts "pub let PRINT_STARTS: [i64] = [#{starts.join(", ")}]"
puts ""
puts "/// Where each such run ends (exclusive)."
puts "pub let PRINT_ENDS: [i64] = [#{ends.join(", ")}]"
