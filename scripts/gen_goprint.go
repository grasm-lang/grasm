// Writes the code points Go's strconv.IsPrint refuses into packages/goquote.
//
// Whether a rune is printable depends on the Unicode tables of the Go that
// answers, so they are read from that Go rather than typed, and regenerated
// when it changes:
//
//	go run scripts/gen_goprint.go packages/goquote/src/main.gr
//
// The ranges replace whatever is between the `BEGIN GENERATED` and
// `END GENERATED` lines of the file. With `-check` nothing is written and the
// exit status says whether the file is current.
package main

import (
	"fmt"
	"os"
	"runtime"
	"strconv"
	"strings"
	"unicode"
)

func ranges(keep func(rune) bool) [][2]rune {
	var out [][2]rune
	start := rune(-1)
	for r := rune(0); r <= unicode.MaxRune; r++ {
		in := keep(r)
		if in && start < 0 {
			start = r
		}
		if !in && start >= 0 {
			out = append(out, [2]rune{start, r - 1})
			start = -1
		}
	}
	if start >= 0 {
		out = append(out, [2]rune{start, unicode.MaxRune})
	}
	return out
}

func packed(name string, rs [][2]rune) []string {
	var parts []string
	for _, p := range rs {
		parts = append(parts, fmt.Sprintf("%x-%x", p[0], p[1]))
	}
	all := strings.Join(parts, ",")
	lines := []string{fmt.Sprintf("let %s = \"\" +", name)}
	for i := 0; i < len(all); i += 64 {
		end := min(i+64, len(all))
		tail := " +"
		if end == len(all) {
			tail = ""
		}
		lines = append(lines, fmt.Sprintf("\"%s\"%s", all[i:end], tail))
	}
	return lines
}

func main() {
	check := len(os.Args) > 2 && os.Args[1] == "-check"
	path := os.Args[len(os.Args)-1]
	raw, err := os.ReadFile(path)
	if err != nil {
		fmt.Println(err)
		os.Exit(1)
	}
	source := string(raw)
	begin := strings.Index(source, "// BEGIN GENERATED")
	end := strings.Index(source, "// END GENERATED")
	if begin < 0 || end < begin {
		fmt.Println("no GENERATED markers in", path)
		os.Exit(1)
	}
	hidden := ranges(func(r rune) bool { return !strconv.IsPrint(r) })
	graphic := ranges(func(r rune) bool { return !strconv.IsPrint(r) && strconv.IsGraphic(r) })
	lines := []string{fmt.Sprintf("// BEGIN GENERATED by scripts/gen_goprint.go from %s, Unicode %s",
		runtime.Version(), unicode.Version)}
	lines = append(lines, packed("GO_HIDDEN_PACKED", hidden)...)
	lines = append(lines, packed("GO_GRAPHIC_PACKED", graphic)...)
	block := strings.Join(lines, "\n") + "\n"
	updated := source[:begin] + block + source[end:]
	if check {
		if updated != source {
			fmt.Println(path, "is stale: run go run scripts/gen_goprint.go", path)
			os.Exit(1)
		}
		return
	}
	if err := os.WriteFile(path, []byte(updated), 0o644); err != nil {
		fmt.Println(err)
		os.Exit(1)
	}
	fmt.Printf("%d ranges Go will not print, %d it calls graphic anyway\n", len(hidden), len(graphic))
}
