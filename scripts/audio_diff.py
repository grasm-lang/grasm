"""`audiodsp` against ffmpeg's filters, sample by sample.

Every answer comes from running ffmpeg on this machine. The source material is
ffmpeg's too — a sine under pink noise, generated by `lavfi` — so nothing in
the comparison was produced by the code under test.

Both sides write 32-bit files. Reducing bit depth is where an encoder decides
whether to dither, and two programs that dither differently disagree
everywhere for reasons that have nothing to do with the filter; widening has
no such decision.

ffmpeg is also asked to filter in double precision. Two reasons, and the
second one was found here rather than assumed:

  - Left alone, ffmpeg keeps the input's sample format through a filter that
    supports it, so a 16-bit file is filtered in 16-bit and every comparison
    sits on a floor of exactly one 16-bit step — 3.05e-05, the same number for
    every case, which is a measurement of the file format and not of the code.

  - In 32-bit float, one case disagreed by 3.15e-05: a low-pass at 80 Hz with
    Q 2. That filter's poles sit very close to the unit circle at 44.1 kHz, so
    direct form I loses significance in single precision. In double both sides
    agree to 2e-7. The disagreement was ffmpeg's precision, not this package's
    arithmetic — and it is the reason `audiodsp` keeps every buffer in f64
    rather than following the sample width in from the file.

The tolerance is 1e-6 of full scale, which is under half a 24-bit step and
roughly 140 dB below the signal. Anything louder than that is arithmetic that
does not match, not rounding.
"""
import os
import struct
import subprocess
import sys
import tempfile
import wave

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
GRASM = os.environ.get("GRASM", os.path.join(ROOT, "target/release/grasm"))
TOLERANCE = 1e-6
RATE = 44100

# name, our arguments, ffmpeg's filter string
CASES = [
    ("gain -6 dB", ["gain", "-6"], "volume=-6dB"),
    ("gain +3.5 dB", ["gain", "3.5"], "volume=3.5dB"),
    ("gain -0.25 dB", ["gain", "-0.25"], "volume=-0.25dB"),
    # Coefficients handed to both, so only the difference equation is tested.
    ("biquad, explicit coefficients",
     ["biquad", "0.2", "0.4", "0.2", "-0.5", "0.25"],
     "biquad=b0=0.2:b1=0.4:b2=0.2:a0=1:a1=-0.5:a2=0.25"),
    ("biquad, a near-unstable pair",
     ["biquad", "1.0", "-1.9", "0.9025", "-1.88", "0.89"],
     "biquad=b0=1:b1=-1.9:b2=0.9025:a0=1:a1=-1.88:a2=0.89"),
    ("lowpass 1 kHz, Q 0.7071", ["lowpass", "1000", "0.7071"],
     "lowpass=f=1000:width_type=q:w=0.7071:p=2"),
    ("lowpass 80 Hz, Q 2", ["lowpass", "80", "2"],
     "lowpass=f=80:width_type=q:w=2:p=2"),
    ("highpass 3 kHz, Q 0.5", ["highpass", "3000", "0.5"],
     "highpass=f=3000:width_type=q:w=0.5:p=2"),
    ("bandpass 1 kHz, Q 1", ["bandpass", "1000", "1"],
     "bandpass=f=1000:width_type=q:w=1"),
    ("peaking 2 kHz, Q 1, +6 dB", ["peaking", "2000", "1", "6"],
     "equalizer=f=2000:width_type=q:w=1:g=6"),
    ("peaking 500 Hz, Q 0.5, -9 dB", ["peaking", "500", "0.5", "-9"],
     "equalizer=f=500:width_type=q:w=0.5:g=-9"),
    ("fade in, linear", ["fade", "in", "tri", "8000"],
     "afade=t=in:start_sample=0:nb_samples=8000:curve=tri"),
    ("fade in, quarter sine", ["fade", "in", "qsin", "8000"],
     "afade=t=in:start_sample=0:nb_samples=8000:curve=qsin"),
    ("fade in, half sine", ["fade", "in", "hsin", "8000"],
     "afade=t=in:start_sample=0:nb_samples=8000:curve=hsin"),
    ("fade in, logarithmic", ["fade", "in", "log", "8000"],
     "afade=t=in:start_sample=0:nb_samples=8000:curve=log"),
    ("fade in, exponential", ["fade", "in", "exp", "8000"],
     "afade=t=in:start_sample=0:nb_samples=8000:curve=exp"),
    ("fade in, square root", ["fade", "in", "squ", "8000"],
     "afade=t=in:start_sample=0:nb_samples=8000:curve=squ"),
    ("fade in, quadratic", ["fade", "in", "qua", "8000"],
     "afade=t=in:start_sample=0:nb_samples=8000:curve=qua"),
    ("fade in, cubic", ["fade", "in", "cub", "8000"],
     "afade=t=in:start_sample=0:nb_samples=8000:curve=cub"),
    ("fade in, parabola", ["fade", "in", "par", "8000"],
     "afade=t=in:start_sample=0:nb_samples=8000:curve=par"),
    ("echo, one tap", ["echo", "0.8", "0.9", "60", "0.4"],
     "aecho=0.8:0.9:60:0.4"),
    ("echo, three taps", ["echo", "0.6", "0.7", "40,90,150", "0.5,0.3,0.2"],
     "aecho=0.6:0.7:40|90|150:0.5|0.3|0.2"),
]


def read_wav(path):
    with wave.open(path, "rb") as w:
        width = w.getsampwidth()
        data = w.readframes(w.getnframes())
    fmt = {2: "<h", 4: "<i"}[width]
    step = struct.calcsize(fmt)
    scale = float(1 << (8 * width - 1))
    return [struct.unpack_from(fmt, data, i)[0] / scale
            for i in range(0, len(data), step)]


def run(argv, why):
    done = subprocess.run(argv, capture_output=True, text=True)
    if done.returncode != 0:
        print("  %s failed: %s" % (why, done.stderr.strip()[-400:]))
        return False
    return True


def main():
    if subprocess.run(["which", "ffmpeg"], capture_output=True).returncode != 0:
        print("ffmpeg is not installed — nothing to compare against")
        return 1

    work = tempfile.mkdtemp()
    harness = os.path.join(work, "audiotest")
    built = subprocess.run([GRASM, "build", "packages/audiotest/src/main.gr",
                            "--native", "-o", harness], cwd=ROOT,
                           capture_output=True, text=True)
    if built.returncode != 0:
        print(built.stderr[-1500:])
        return 1

    source = os.path.join(work, "source.wav")
    if not run(["ffmpeg", "-v", "error",
                "-f", "lavfi", "-i",
                "sine=frequency=440:duration=2:sample_rate=%d" % RATE,
                "-f", "lavfi", "-i",
                "anoisesrc=d=2:c=pink:r=%d:a=0.35:seed=7" % RATE,
                "-filter_complex", "amix=inputs=2",
                "-c:a", "pcm_s16le", "-y", source], "source"):
        return 1

    passed = 0
    failed = 0
    worst = []
    for name, ours, theirs in CASES:
        mine = os.path.join(work, "mine.wav")
        yours = os.path.join(work, "theirs.wav")
        if not run([harness, ours[0], source, mine] + ours[1:], name):
            failed += 1
            continue
        # ffmpeg keeps the input's sample format through a filter when the
        # filter supports it, so a 16-bit file is filtered in 16-bit and every
        # comparison sits on a floor of exactly one 16-bit step. Asking for
        # float first is what makes this a comparison of the arithmetic.
        chain = "aformat=sample_fmts=dblp," + theirs
        if not run(["ffmpeg", "-v", "error", "-i", source, "-af", chain,
                    "-c:a", "pcm_s32le", "-y", yours], name):
            failed += 1
            continue
        a = read_wav(mine)
        b = read_wav(yours)
        if not a or not b:
            print("  FAIL  %s — one side wrote nothing" % name)
            failed += 1
            continue
        # An echo's tail may be trimmed differently at the very end; compare
        # the samples both produced and report the lengths when they differ.
        n = min(len(a), len(b))
        gap = max(abs(a[i] - b[i]) for i in range(n))
        if gap <= TOLERANCE and abs(len(a) - len(b)) <= 1:
            print("  ok    %-34s worst sample %.2e" % (name, gap))
            passed += 1
        else:
            print("  FAIL  %-34s worst sample %.2e  (%d vs %d samples)"
                  % (name, gap, len(a), len(b)))
            failed += 1
        worst.append((gap, name))

    print()
    if worst:
        top = max(worst)
        print("audio_diff: %d passed, %d failed, %d cases against ffmpeg "
              "(worst %.2e, %s)" % (passed, failed, len(CASES), top[0], top[1]))
    return 1 if failed else 0


if __name__ == "__main__":
    sys.exit(main())
