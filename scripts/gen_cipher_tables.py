"""Generate the constant tables of the B33 block ciphers into their packages.

Every table comes from somewhere checkable, never from memory:

- Blowfish's P-array and S-boxes are the hexadecimal digits of pi, computed
  here (Machin's formula) and compared with golang.org/x/crypto/blowfish.
- CAST5's eight S-boxes and RC2's PITABLE are read from x/crypto's source
  in the module cache.
- SM4's S-box, Camellia's s1, ARIA's second S-box and SEED's S1 and S2 are
  found in OpenSSL's libcrypto by shape alone (a run of 256 values that is
  a permutation, read as bytes, as one byte lane of a 32-bit table, or as
  the OR of each 32-bit word's bytes), and a candidate is kept only if a
  reference model of the cipher built on it (scripts/lib/cipher_models.py)
  encrypts exactly as OpenSSL does at every key size.

Each table goes below a marker line at the end of its package. With
--check nothing is written, and the exit status says whether the
packages are current.
"""
import glob
import os
import random
import re
import subprocess
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(ROOT, "scripts/lib"))
import cipher_models as M  # noqa: E402
import evp  # noqa: E402

MARKER = "// --- Generated by scripts/gen_cipher_tables.py; do not edit below this line. ---"


def go_crypto():
    cache = subprocess.run(["go", "env", "GOMODCACHE"], capture_output=True, text=True, cwd="/").stdout.strip()
    dirs = sorted(glob.glob(os.path.join(cache, "golang.org/x/crypto@v*")),
                  key=lambda d: [int(x) for x in re.findall(r"\d+", d.split("@v")[1])[:3]])
    if not dirs:
        raise SystemExit("golang.org/x/crypto is not in the module cache")
    return dirs[-1]


def go_array(path, name):
    src = open(path).read()
    m = re.search(r"var " + re.escape(name) + r" = \[[^\]]*\][\w\[\]]*\{(.*?)\n\}", src, re.S)
    body = re.sub(r"//[^\n]*", "", m.group(1))
    return [int(x, 0) for x in re.findall(r"0x[0-9a-fA-F]+|\b\d+\b", body)]


def pi_hex_words(count):
    """The first `count` 32-bit words of pi's fractional hex digits."""
    bits = 32 * count + 64
    one = 1 << bits

    def arctan_inv(x):
        total, term, k, sign = 0, one // x, 1, 1
        while term:
            total += sign * (term // k)
            term //= x * x
            k += 2
            sign = -sign
        return total
    pi = 16 * arctan_inv(5) - 4 * arctan_inv(239)
    frac = pi - 3 * one
    return [(frac >> (bits - 32 * (i + 1))) & 0xFFFFFFFF for i in range(count)]


def scan_permutations():
    data = open(evp._path, "rb").read()

    def perms(stream):
        out, count, distinct = [], [0] * 256, 0
        for i, v in enumerate(stream):
            if count[v] == 0:
                distinct += 1
            count[v] += 1
            if i >= 256:
                u = stream[i - 256]
                count[u] -= 1
                if count[u] == 0:
                    distinct -= 1
            if i >= 255 and distinct == 256:
                out.append(tuple(stream[i - 255:i + 1]))
        return out
    plain = set(perms(data))
    for start in range(4):
        plain |= set(perms(data[start::4]))
    words = [data[i] | data[i + 1] | data[i + 2] | data[i + 3] for i in range(0, len(data) - 3, 4)]
    return [list(p) for p in plain], [list(p) for p in set(perms(words))]


def only(label, cands, fits):
    hits = [c for c in cands if fits(c)]
    if len(hits) != 1:
        raise SystemExit(f"{label}: {len(hits)} candidate tables fit OpenSSL, not exactly one")
    return hits[0]


def agrees(name, model, keylens):
    rng = random.Random(name)
    for kl in keylens:
        for _ in range(3):
            key, block = bytes(rng.randrange(256) for _ in range(kl)), bytes(rng.randrange(256) for _ in range(16))
            if model(key, block) != evp.cipher(f"{name.replace('*', str(kl * 8))}", key, None, block):
                return False
    return True


def tables():
    out = {}
    plain, ored = scan_permutations()
    out["sm4"] = {"SM4_SBOX": only("SM4", plain, lambda s: agrees("SM4-ECB", lambda k, b: M.sm4_enc(s, k, b), [16]))}
    out["camellia"] = {"CAMELLIA_S1": only("Camellia", plain, lambda s: agrees(
        "CAMELLIA-*-ECB", lambda k, b: M.cam_enc(s, k, b), [16, 24, 32]))}
    # ARIA's first S-box is AES's; only the second is looked for.
    s1 = None
    for c in plain:
        if c[:4] == [0x63, 0x7c, 0x77, 0x7b]:
            s1 = c
    out["aria"] = {"ARIA_S2": only("ARIA", plain, lambda s: agrees(
        "ARIA-*-ECB", lambda k, b: M.aria_enc(s1, s, k, b), [16, 24, 32]))}
    pairs = [(a, b) for a in ored for b in ored if a != b]
    seed = only("SEED", pairs, lambda p: agrees("SEED-ECB", lambda k, b: M.seed_enc(p[0], p[1], k, b), [16]))
    out["seed"] = {"SEED_S1": seed[0], "SEED_S2": seed[1]}

    xc = go_crypto()
    bf = [go_array(f"{xc}/blowfish/const.go", n) for n in ("p", "s0", "s1", "s2", "s3")]
    digits = pi_hex_words(18 + 4 * 256)
    if sum(bf, []) != digits:
        raise SystemExit("Blowfish: x/crypto's tables are not pi's digits")
    out["blowfish"] = {"BLOWFISH_PI": digits}
    cast = go_array(f"{xc}/cast5/cast5.go", "sBox")
    if len(cast) != 8 * 256:
        raise SystemExit(f"CAST5: {len(cast)} S-box entries, not 2048")
    out["cast5"] = {"CAST5_S": cast}
    rc2 = go_array(f"{xc}/pkcs12/internal/rc2/rc2.go", "piTable")
    if sorted(rc2) != list(range(256)):
        raise SystemExit("RC2: PITABLE is not a permutation")
    out["rc2"] = {"RC2_PITABLE": rc2}
    return out


def render(name, values, wide):
    per = 8 if wide else 16
    fmt = (lambda v: f"0x{v:08x}") if wide else (lambda v: str(v))
    lines = [f"let {name} = ["]
    for i in range(0, len(values), per):
        lines.append("    " + ", ".join(fmt(v) for v in values[i:i + per]) + ",")
    lines.append("]")
    return "\n".join(lines)


def main():
    check = "--check" in sys.argv
    stale = []
    for pkg, tabs in tables().items():
        path = os.path.join(ROOT, "packages", pkg, "src", "main.gr")
        src = open(path).read()
        head = src.split(MARKER)[0].rstrip("\n")
        body = "\n\n".join(render(n, v, max(v) > 255) for n, v in tabs.items())
        new = f"{head}\n\n{MARKER}\n\n{body}\n"
        if new != src:
            stale.append(pkg)
            if not check:
                open(path, "w").write(new)
    if check and stale:
        print("stale tables:", " ".join(stale)); sys.exit(1)
    print("tables current" if check else f"wrote: {' '.join(stale) or 'nothing'}")


if __name__ == "__main__":
    main()
