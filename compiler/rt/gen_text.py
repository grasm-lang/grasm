#!/usr/bin/env python3
"""Writes compiler/rt/src/text.gr: the runtime's fixed text as code.

The runtime is written over raw memory and holds no Grasm `str` -- a `str`
literal is a value the runtime itself would have to make -- and Grasm has no
static byte data. So each piece of fixed text is a function that stores it,
eight bytes at a time, at an address it is given, and answers its length.
Run this after changing TEXTS; the gate `rtswap` checks the file is current.
"""
import sys

TEXTS = [
    ("div_zero", "division by zero"),
    ("rem_zero", "remainder by zero"),
    ("assert_failed", "assertion failed"),
    ("neg_pow", "negative integer exponent (use floats)"),
    ("uaf_inc", "use after free: inc on a value already released"),
    ("uaf_dec", "use after free: dec on a value already released"),
    ("true_word", "true"),
    ("false_word", "false"),
    ("nan_word", "NaN"),
    ("inf_word", "inf"),
    ("byte_len_not_str", "byte_len on non-string"),
    ("expected_str", "expected a string"),
    ("len_not_str", "len on non-string"),
]


def words(text):
    b = text.encode("utf-8")
    b += b"\0" * (-len(b) % 8)
    for i in range(0, len(b), 8):
        yield int.from_bytes(b[i:i + 8], "little")


def main():
    out = [
        "// Generated by compiler/rt/gen_text.py; do not edit.",
        "//",
        "// Fixed text, stored at `at` eight bytes at a time (zero-padded to a",
        "// multiple of eight, so `at` must have room for that); each answers the",
        "// text's length in bytes.",
        "",
    ]
    for name, text in TEXTS:
        n = len(text.encode("utf-8"))
        out.append(f"/// `{text}`")
        out.append(f"pub fn {name}(at: addr) -> i64 {{")
        out.append("    unsafe {")
        for k, w in enumerate(words(text)):
            out.append(f"        at.offset({8 * k}).store_u64(0x{w:016x})")
        out.append("    }")
        out.append(f"    {n}")
        out.append("}")
        out.append("")
    sys.stdout.write("\n".join(out))


if __name__ == "__main__":
    main()
