import sys
n = int(sys.argv[1]); o = []
o.append("#[derive(Clone)] struct Rec { id: i64, name: String, score: f64 }")
o.append("enum Kind { Small(i64), Wide(i64, i64), Text(String) }")
for i in range(n):
    o.append("fn classify_%d(k: &Kind) -> i64 {" % i)
    o.append("    match k {")
    o.append("        Kind::Small(n) => n * %d," % (i % 7 + 2))
    o.append("        Kind::Wide(a, b) => a + b - %d," % (i % 5))
    o.append("        Kind::Text(s) => s.len() as i64,")
    o.append("    }")
    o.append("}")
    o.append("")
    o.append("fn fold_%d(xs: &[i64]) -> i64 {" % i)
    o.append("    let mut total = 0;")
    o.append("    for x in xs {")
    o.append("        if x %% 2 == 0 { total = total + x * %d; } else { total = total - x; }" % (i % 3 + 1))
    o.append("    }")
    o.append("    total")
    o.append("}")
    o.append("")
    o.append("fn build_%d(seed: i64) -> Rec {" % i)
    o.append("    let s = seed * %d + 1;" % (i % 11 + 3))
    o.append("    Rec { id: s, name: format!(\"row {}\", s), score: s as f64 * 0.5 }")
    o.append("}")
    o.append("")
o.append("fn main() {")
o.append("    let mut acc = 0i64;")
for i in range(0, n, max(1, n // 40)):
    o.append("    acc += classify_%d(&Kind::Small(%d)) + fold_%d(&[1,2,3]) + build_%d(%d).id;" % (i, i % 9, i, i, i))
o.append("    println!(\"{}\", acc);")
o.append("}")
print("\n".join(o))
