import sys
n = int(sys.argv[1])          # number of functions
out = []
out.append("// Generated: realistic Grasm, not one line repeated.")
out.append("type Rec = { id: i64, name: str, score: f64 }")
out.append("")
out.append("type Kind =")
out.append("    | Small(n: i64)")
out.append("    | Wide(a: i64, b: i64)")
out.append("    | Text(s: str)")
out.append("")
for i in range(n):
    out.append("fn classify_%d(k: Kind) -> i64 {" % i)
    out.append("    match k {")
    out.append("        Small(n) -> n * %d" % (i % 7 + 2))
    out.append("        Wide(a, b) -> a + b - %d" % (i % 5))
    out.append("        Text(s) -> s.len()")
    out.append("    }")
    out.append("}")
    out.append("")
    out.append("fn fold_%d(xs: [i64]) -> i64 {" % i)
    out.append("    var total = 0")
    out.append("    for x in xs {")
    out.append("        if x % 2 == 0 {")
    out.append("            total = total + x * %d" % (i % 3 + 1))
    out.append("        } else {")
    out.append("            total = total - x")
    out.append("        }")
    out.append("    }")
    out.append("    total")
    out.append("}")
    out.append("")
    out.append("fn build_%d(seed: i64) -> Rec {" % i)
    out.append("    let s = seed * %d + 1" % (i % 11 + 3))
    out.append("    Rec{ id: s, name: \"row {s}\", score: s.as_f64() * 0.5 }")
    out.append("}")
    out.append("")
out.append("fn main() / {io} {")
out.append("    var acc = 0")
for i in range(0, n, max(1, n // 40)):
    out.append("    acc = acc + classify_%d(Small(%d)) + fold_%d([1, 2, 3]) + build_%d(%d).id" % (i, i % 9, i, i, i))
out.append("    print(\"{acc}\")")
out.append("}")
print("\n".join(out))
